def rename(old, new):
    for path in (p("data", "WorldMap.ini"), p("data", "Quests.ini"), os.path.join(HERE, "build_zones.py")):
        b = open(path, "rb").read()
        enc = "utf-8" if path.endswith(".py") else "cp1252"
        t = b.decode(enc)
        t2 = t.replace(old, new).replace("the Dustlands", "the Sallow Waste").replace("by the Dustlands", "by the Sallow Waste")
        if t2 != t:
            open(path, "wb").write(t2.encode(enc))


