def fishing(world, rng, taken, count):
    """Spots in open water beside land, away from where they are already."""
    done = 0
    for _ in range(9000):
        if done >= count:
            break
        gx, gy = rng.randint(5 * XT, 28 * XT), rng.randint(-6 * YT, 21 * YT)
        world.get_map(gx // XT, gy // YT)
        c = world.cell(gx, gy)
        if c != "Water001" or (gx, gy) in taken:
            continue
        beside = [world.cell(gx + dx, gy + dy) or "" for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
        if not any(b.startswith(("Grass", "Sand")) for b in beside):
            continue
        far = math.hypot(gx / XT - 4, gy / YT - 6)
        world.line(gx, gy, "StaticObject", rng.choice(("Fish_Spot", "Trout_Spot")) if far < 14 else rng.choice(("Salmon_Spot", "Swordfish_Spot")))
        taken.add((gx, gy))
        done += 1
    return done


def add_labels(names):
    path = p("data", "WorldMap.ini")
    text = open(path, "rb").read().decode("cp1252")
    for title, where in names:
        if ("\r\n%s=" % title) not in text:
            head = "[Regions]\r\n" if "[Regions]\r\n" in text else "[Places]\r\n"
            at = text.index(head) + len(head) if head in text else len(text)
            text = text[:at] + "%s=%s\r\n" % (title, where) + text[at:]
    open(path, "wb").write(text.encode("cp1252"))


def mineral_moves(world):
    """Mithril and gems lie only in the hard zones above ground now."""
    n = 0
    for path in glob.glob(p("maps", "*,0.txt")):
        name = os.path.basename(path)[:-4]
        if name in world.maps:
            m = world.maps[name]
        else:
            b = open(path, "rb").read()
            if b"Mithril_Rock001" not in b and b"Gem_Rock001" not in b:
                continue
            mx, my, _ = W.mxyz(name)
            m = world.get_map(mx, my)
        for y, row in enumerate(m.rows):
            for x, c in enumerate(row):
                if "Mithril_Rock001" in c or "Gem_Rock001" in c:
                    row[x] = c.replace("Mithril_Rock001", "Ore_Rock001").replace("Gem_Rock001", "Silver_Rock001")
                    n += 1
    return n


