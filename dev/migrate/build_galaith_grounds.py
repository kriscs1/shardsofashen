# ================================================================== pictures: small helpers
def clamp(c):
    return tuple(max(0, min(255, int(v))) for v in c)


def shade(c, k):
    return clamp((c[0] * k, c[1] * k, c[2] * k))


def new(w=S, h=S):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def outlined(im, colour=(30, 26, 28, 255)):
    """The 1 px dark outline every object has: a mask of the picture, grown by one, behind it."""
    out = new(*im.size)
    px, src = out.load(), im.load()
    w, h = im.size
    for y in range(h):
        for x in range(w):
            if src[x, y][3] > 0:
                continue
            if any(0 <= x + dx < w and 0 <= y + dy < h and src[x + dx, y + dy][3] > 120
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                px[x, y] = colour
    out.alpha_composite(im)
    return out


def tile(name, im):
    """A tile's picture, and its colour on the minimap (what's see-through not counted: the ground under it shows)."""
    px = np.array(im.convert("RGBA")).reshape(-1, 4)
    px = px[px[:, 3] > 120]
    colour = tuple(int(v) for v in px[:, :3].mean(axis=0)) if len(px) else (120, 120, 120)
    SK.minimap_colour(name, colour)
    return write_image(p("sprites", "Tiles", name + ".png"), im, decor=True)


def entity(name, im):
    return write_image(p("sprites", "Entities", name + ".png"), im)


