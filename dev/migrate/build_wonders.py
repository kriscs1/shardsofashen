def find_place(name):
    for path in glob.glob(p("maps", "*.map")):
        for ln in open(path, "rb").read().decode("cp1252").split("\r\n"):
            if ln.startswith("Id\t%s\t" % name):
                f = ln.split("\t")
                return os.path.basename(path)[:-4], int(f[2]), int(f[3])
    return None


def free_near(m, tx, ty):
    for r in range(1, 8):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                x, y = tx + dx, ty + dy
                if 1 <= x <= XT and 1 <= y <= YT:
                    c = m.rows[y - 1][x - 1]
                    if "+" not in c and c.split("+")[0].startswith(("Grass", "Flagstone", "Cobble", "Marble", "Noble", "Royal", "Sand", "Snow", "Plank", "Tile", "Ash", "Cinder", "Gravel", "Dirt")):
                        taken = any(ln.split("\t")[0] in ("NPC", "StaticObject") and (int(float(ln.split("\t")[2])) // 32 + 1, int(float(ln.split("\t")[3])) // 32 + 1) == (x, y)
                                    for ln in m.ents if ln.split("\t")[0] in ("NPC", "StaticObject"))
                        if not taken:
                            return x, y
    return None


def place_things():
    made = 0
    for k, (place, _) in enumerate(NOTES, 1):
        pid = "Mary_Note_%d" % k
        at = find_place(place)
        if at is None:
            print("No place", place)
            continue
        m = Map(at[0])
        if any("Id=%s" % pid in ln for ln in m.ents):
            continue
        spot = free_near(m, at[1], at[2])
        if spot is None:
            print("No room by", place)
            continue
        m.ents.append(obj_line("StaticObject", "Mary_Note", spot[0], spot[1], "Id=%s" % pid))
        m.save()
        made += 1
    # (the Mirror Tarn's stone)
    tarn = find_place("Mirror_Tarn")
    if tarn and not find_place("Marys_Cache"):
        m = Map(tarn[0])
        spot = free_near(m, tarn[1], tarn[2])
        if spot:
            c = m.rows[spot[1] - 1][spot[0] - 1]
            m.rows[spot[1] - 1][spot[0] - 1] = c.split("+")[0] + "+Decor(Rock001)"
            m.ents.append("Id\tMarys_Cache\t%d\t%d" % spot)
            m.save()
    # (the champion's statue, on the boulevard by the fountain)
