def mob_stats(level, kind):
    return dict(Hitpoints=round(8.3 * level), Strength=max(1, round(0.68 * level)), Defence=max(1, round(0.75 * level)))


def tint(im, col):
    """A picture in another colour, as light and dark as it was; its dark outline stays."""
    a = np.array(im.convert("RGBA"), dtype=np.float32)
    lum = (a[..., 0] * 0.3 + a[..., 1] * 0.59 + a[..., 2] * 0.11)
    k = np.clip(lum / 150.0, 0, 1.45)[..., None]
    out = np.array(col, dtype=np.float32)[None, None, :] * k
    rgb = np.where((lum < 42)[..., None], a[..., :3], out)
    a[..., :3] = np.clip(rgb, 0, 255)
    return Image.fromarray(a.astype(np.uint8), "RGBA")


