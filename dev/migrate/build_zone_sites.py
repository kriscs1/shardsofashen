# ================================================================== the old keeps
def keeps(world, rng, taken):
    """Each old keep a keep: a stone hall, roofed, with its yard; whoever holds it still holds it."""
    n = 0
    for path in glob.glob(p("maps", "*,0.txt")):
        b = open(path, "rb").read()
        if b"Old_Keep_" not in b:
            continue
        mx, my, _ = W.mxyz(os.path.basename(path)[:-4])
        m = world.get_map(mx, my)
        for ln in m.ents:
            f = ln.split("\t")
            if f[0] != "Id" or not f[1].startswith("Old_Keep_"):
                continue
            x, y = int(f[2]), int(f[3])
            x1 = max(2, min(XT - 10, x - 4))
            y1 = max(2, min(YT - 8, y - 4))
            for yy in range(y1 - 1, y1 + 8):
                for xx in range(x1 - 1, x1 + 10):
                    c = m.rows[yy - 1][xx - 1]
                    m.rows[yy - 1][xx - 1] = c.split("+")[0]
            K.building(m, x1, y1, x1 + 8, y1 + 5, x1 + 4, wall="Stone_Wall001", roof="Slate")
            for name, dx in (("Banner001", 2), ("Table001", 4), ("Barrel001", 6)):
                m.set(x1 + dx, y1 + 1 if name != "Table001" else y1 + 3, decor=name)
            m.set(x1 + 1, y1 + 7, decor="Campfire001")
            m.set(x1 + 7, y1 + 7, decor="Barrel002")
            yard = [(xx, y1 + 7) for xx in range(x1 + 2, x1 + 7)] + [(xx, y1 + 6) for xx in range(x1, x1 + 9) if xx != x1 + 4]
            for k, ln in enumerate(list(m.ents)):               # (whoever stood where the walls are now: in the yard)
                g = ln.split("\t")
                if g[0] not in ("NPC", "StaticObject") or len(g) < 4:
                    continue
                tx, ty = int(float(g[2]) + 16) // 32 + 1, int(float(g[3]) + 28) // 32 + 1
                inside = x1 <= tx <= x1 + 8 and y1 <= ty <= y1 + 5
                if inside and (ty in (y1, y1 + 5) or tx in (x1, x1 + 8)) and yard:
                    ax, ay = yard.pop(0)
                    g[2], g[3] = str((ax - 1) * 32), str((ay - 1) * 32 - (8 if g[0] == "NPC" else 0))
                    m.ents[m.ents.index(ln)] = "\t".join(g)
            n += 1
    return n


