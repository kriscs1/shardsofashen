def salt_tile():
    """A salt pan: white crust broken into plates, a little dust in the cracks."""
    rng = random.Random(83)
    ridges = 1 - np.abs(2 * soft(rng, 384, 2.0) - 1)
    v = stretch(0.65 * stretch(soft(rng, 384, 1.6)) + 0.35 * stretch(soft(rng, 384, 0.7, low=0.1)))
    v = np.clip(steps(v, 5) - 0.55 * (ridges > 0.93) + 0.12 * specks(rng, v.shape, 384 * 384 // 90, 1), 0, 1)
    arr = ramp(v, [(0.0, (150, 140, 124)), (0.35, (208, 202, 188)), (0.6, (222, 218, 206)), (0.85, (232, 229, 219)),
                   (1.0, (242, 240, 232))]).astype(np.uint8)
    save_texture("Salt", arr)
    SK.save("Tiles", "Salt_Flat001", [[tuple(int(c) for c in arr[y, x]) for x in range(32)] for y in range(32)])
    tiles = Ini(p("data", "Tiles.ini"))
    for k, v2 in (("Texture", "Salt"), ("Walkable.Data", "1" * 49), ("Show.Name", "0"), ("Use.Words", ""), ("Blend", "4"),
                  ("Blend.Texture", "Salt_Flat001"), ("Examine.Info", "A salt pan: a crust of white that crunches underfoot."),
                  ("Line.of.Sight", "1"), ("Round", "1")):
        tiles.set("Salt_Flat001", k, v2, overwrite=False)
    tiles.save(p("data", "Tiles.ini"))
    K.minimap_colour("Salt_Flat001", (226, 222, 210))


