def place_label(group, label, where):
    """data\\WorldMap.ini: a label on the world map (group Towns, Regions or Places)."""
    if ini.read(group, label, "<unset>", WORLDMAP) != where:
        ini.write(group, label, where, WORLDMAP)


def drop_label(group, label):
    blocks = _blocks(WORLDMAP)
    for i, b in enumerate(blocks):
        if b.startswith("[%s]\n" % group):
            lines = [ln for ln in b.split("\n") if not ln.startswith(label + "=")]
            blocks[i] = "\n".join(lines)
    _write_blocks(WORLDMAP, blocks)


