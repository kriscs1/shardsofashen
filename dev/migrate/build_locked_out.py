def data():
    tiles = Ini(p("data", "Tiles.ini"))
    for key, v in (("Walkable.Data", "1" * 49), ("Show.Name", "1"), ("Use.Words", ""),
                   ("Examine.Info", "A cellar wall of old stone."), ("Line.of.Sight", "0")):
        tiles.set("Stone_Wall_Hollow001", key, v, overwrite=False)
    tiles.save(p("data", "Tiles.ini"))
    ents = Ini(p("data", "Entities.ini"))
    for key, v in (("Type", "StaticObject"), ("Display.Name", "Key Hook"), ("Use.Words", "Take,Examine"),
                   ("Examine.Info", "A hook by the door, where a sensible man keeps his spare key."), ("Solid", "0")):
        ents.set("Osric_Key_Hook", key, v, overwrite=False)
    ents.save(p("data", "Entities.ini"))
    path = p("data", "Quests.ini")
    text = open(path, "rb").read().decode("cp1252")
    if "[%s]" % QUEST not in text:
        text = text.rstrip("\r\n") + "\r\n\r\n" + QUEST_TEXT.replace("\n", "\r\n")
        open(path, "wb").write(text.encode("cp1252"))
    for name, lines in SCRIPTS.items():
        with open(p("data", "Scripts", name + ".script"), "w", encoding="cp1252", newline="\r\n") as f:
            f.write(HEADER + "\n" + "\n".join(filled(lines)) + "\n")


