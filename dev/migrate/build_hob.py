def make_art():
    """Hob: the Hermit in muddy rags (sprites\\Entities and the 12 walking frames in sprites\\Walk); the Calming_Draught
    (a Basic_Potion turned violet) and Hobs_Diary (the Caravan_Ledger in green leather)."""
    import os
    import sprite_kit as K
    from common import p

    def rags(img):
        return K.hue_shift(img, target_hue=0.08, sat_mul=0.6, val_mul=0.8, pred=lambda c: max(c) - min(c) > 30)

    made = []
    jobs = [("Entities", "Hermit", "Hob", rags)]
    for d in "1248":
        for f in "abc":
            if os.path.exists(p("sprites", "Walk", "Hermit%s%s.png" % (d, f))):
                jobs.append(("Walk", "Hermit" + d + f, "Hob" + d + f, rags))
    jobs.append(("Entities", "Basic_Potion", "Calming_Draught",
                 lambda img: K.hue_shift(img, target_hue=0.75, pred=lambda c: max(c) - min(c) > 40)))
    jobs.append(("Entities", "Caravan_Ledger", "Hobs_Diary",
                 lambda img: K.hue_shift(img, target_hue=0.33, sat_mul=0.8, pred=lambda c: max(c) - min(c) > 30)))
    for kind, src, dst, fn in jobs:
        if K.save(kind, dst, fn(K.load(kind, src))):
            made.append("sprites\\%s\\%s.png" % (kind, dst))
    return made


def extend(world, content, regions):
    global W, C, R
    W, C, R = world, content, regions
    entities()
    place()
    scripts()
    if not any(q[0] == QUEST[0] for q in C.QUESTS):
        C.QUESTS.append(QUEST)
    W.EXTRA_STEPS.insert(0, make_art)
