    for y in range(gy + 2, gy + 10):
        for x in range(gx + 8, gx + 16):
            edge = y in (gy + 2, gy + 9) or x in (gx + 8, gx + 15)
            c = world.cell(x, y)
            if edge:
                world.put(x, y, c + "+Decor(Wood_Fence%03d)" % (1 if y in (gy + 2, gy + 9) else 2))
