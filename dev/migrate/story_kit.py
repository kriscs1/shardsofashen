def ents_without(m, test):
    """Drops m's entity lines for which test(fields) is true; returns how many went."""
    keep = [ln for ln in m.ents if not test(ln.split("\t"))]
    n = len(m.ents) - len(keep)
    m.ents = keep
    return n


def has_id(m, pid):
    return any(("Id=%s" % pid) in ln.split("\t")[-1].split() or ln.split("\t")[:2] == ["Id", pid] for ln in m.ents)


def place_id(m, pid, x, y):
    """An Id line: a place's name for a tile (scripts, quest markers and the world map find it by it)."""
    m.ents = [ln for ln in m.ents if ln.split("\t")[:2] != ["Id", pid]]
    m.ents.append("Id\t%s\t%d\t%d" % (pid, x, y))


THIN = {"nw": "008", "n": "001", "ne": "005", "w": "004", "e": "002"}


def building(m, x1, y1, x2, y2, door, wall="Brick001", roof="Slate", windows=None, chimney=None, upper=None,
             dormers=(), floor="Plank001"):
    """A building whose front (y2) shows below its roof: walls round a floor, thin walls under the roof (inside), the
    door and windows in the front. door: its x. windows: the front's window columns (default every other one from
    the door). chimney: the roof column with a chimney (None: none). upper: a Map for the level above (its floor
    under the same walls, the upper storey's front under the eaves, windows). Returns the roof group."""
    base = V.WALL_BASES[wall]
    thin = "%s_Thin_%s" % (base, "Marble" if floor.startswith("Marble") else "Plank")   # (a palace: marble floors)
    for y in range(y1, y2 + 1):
        for x in range(x1, x2 + 1):
            if y == y2:
                t = wall
            elif y == y1 or x in (x1, x2):
                side = ("n" if y == y1 else "") + ("w" if x == x1 else "e" if x == x2 else "")
                t = thin + THIN[side]
            else:
                t = floor
            m.put(x, y, t, {})
    m.set(door, y2, tile=V.WALL_DOORS[wall] if wall in V.WALL_DOORS else "Door001")
    if windows is None:
        windows = [x for x in range(x1 + 1, x2) if x != door and (x - door) % 2 == 0]
    for wx in windows:
        m.set(wx, y2, decor=V.window_tile(wall))
    g = max(m.groups() | {0}) + 1
    spec = roof
    if upper is not None:
        spec = V.roof_spec(roof, wall, -1 if chimney is None else chimney - x1, [d - x1 for d in dormers])
    rows = V.ROW_KINDS[max(1, min(6, y2 - y1))]
    for y in range(y1, y2):
        for x in range(x1, x2 + 1):
            piece = V.roof_piece(spec, x, y, x1, y1, x2, y2 - 1)
            ridge = rows[min(len(rows) - 1, y - y1)] == ("R" if "R" in rows else rows[0])
            if upper is None and x == chimney and ridge:            # (one storey: the chimney stack on the ridge)
                piece = "%s%03d" % (piece[:-3], int(piece[-3:]) + 15)
            m.set(x, y, roof="%s.%02d" % (piece, g))
    if upper is not None:
        yf = y2 - 1                                     # (the upper storey's front: under the eaves, over the door)
        for y in range(y1, yf + 1):
            for x in range(x1, x2 + 1):
                if y == yf:
                    t = wall
                elif y == y1 or x in (x1, x2):
                    side = ("n" if y == y1 else "") + ("w" if x == x1 else "e" if x == x2 else "")
                    t = thin + THIN[side]
                else:
                    t = floor
                upper.put(x, y, t, {})
        for x in range(x1 + 1, x2):
            if V.upper_window(x, x1, x2):
                upper.set(x, yf, decor=V.window_tile(wall))
    return g


def partition(m, x, ya, yb, gaps=(), wall="Brick001"):
    """An inside wall down the east edge of column x, from row ya to yb, with doorways at gaps."""
    thin = "%s_Thin_Plank" % V.WALL_BASES[wall]
    for y in range(ya, yb + 1):
        if y not in gaps:
            t, over = m.parts(x, y)
            if t == "Plank001":
                m.put(x, y, thin + "002", over)


