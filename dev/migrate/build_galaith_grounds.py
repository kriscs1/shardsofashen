def grand_fountain(frame):
    """The Grand Fountain, standing in the pool: three bowls on a carved stem, water running from each to the next."""
    W, H = FOUNTAIN_SIZE
    im = new(W, H)
    d = ImageDraw.Draw(im)
    cx = W // 2
    stone, lit, dark = (224, 218, 204), (246, 242, 230), (150, 144, 132)

    def bowl(y, rx, ry):
        d.ellipse((cx - rx, y - ry + 3, cx + rx, y + ry + 3), fill=dark)        # (its underside)
        d.ellipse((cx - rx, y - ry, cx + rx, y + ry), fill=stone)
        d.arc((cx - rx, y - ry, cx + rx, y + ry), 180, 360, fill=lit)
        d.ellipse((cx - rx + 3, y - ry + 2, cx + rx - 3, y + ry - 2), fill=WATER_DEEP)
        d.ellipse((cx - rx + 5, y - ry + 3, cx + rx - 5, y + ry - 3), fill=WATER)

    def stem(y0, y1, r):
        d.rectangle((cx - r, y0, cx + r, y1), fill=stone)
        d.line((cx - r, y0, cx - r, y1), fill=lit)
        d.line((cx + r, y0, cx + r, y1), fill=dark)
        d.line((cx + r - 1, y0, cx + r - 1, y1), fill=shade(stone, 0.86))

    bowl(H - 18, 40, 14)                                                         # (the great bowl, in the pool)
    stem(62, H - 20, 6)
    bowl(62, 26, 9)
    stem(38, 60, 4)
    bowl(38, 15, 6)
    stem(16, 36, 2)
    d.ellipse((cx - 5, 9, cx + 5, 19), fill=stone, outline=dark)                 # (the top: a pinecone, its water rising)
    d.ellipse((cx - 3, 11, cx + 2, 15), fill=lit)

    def falling(x, y0, y1, k):
        """A thread of water, its drops running down it."""
        for y in range(y0, y1):
            step = (y + k * 3) % 6
            c = (220, 240, 246, 230) if step < 2 else (150, 204, 226, 200) if step < 4 else (110, 178, 212, 170)
            im.putpixel((x, y), c)
    jet = (1, 3, 4, 2)[frame]
    d.line((cx, 9, cx, 5 - jet), fill=(214, 236, 244, 230))                       # (the jet from the top)
    for k, dx in enumerate((-3, 3)):
        d.point((cx + dx, 7 + ((frame + k) % 3)), fill=(214, 236, 244, 220))
    for k, x in enumerate((cx - 15, cx - 9, cx + 9, cx + 15)):                    # (from the top bowl to the middle)
        falling(x, 42, 58, frame + k)
    for k, x in enumerate((cx - 26, cx - 18, cx - 10, cx + 10, cx + 18, cx + 26)):    # (from the middle to the great)
        falling(x, 66, H - 24, frame + k)
    for k, x in enumerate((cx - 38, cx - 30, cx + 30, cx + 38)):                  # (and from the great bowl to the pool)
        falling(x, H - 16, H - 3, frame + k)
        r = 1 + (frame + k) % 3
        d.arc((x - r * 2, H - 4 - r, x + r * 2, H - 4 + r), 0, 360, fill=WATER_LIT)
    return outlined(im)


