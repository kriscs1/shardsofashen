def farm(world, rng, spot, taken, n):
    from build_isle import roof_over
    gx, gy = spot
    clear_rect(world, gx, gy, 16, 11)
    m = world.get_map(gx // XT, gy // YT)
    x0, y0 = gx % XT + 1, gy % YT + 1
