        "daughter Percy, in Ashford.\\But my eyes aren't what they were, and one road looks like another to me. Would "
        "you walk me there?\tOf course. Follow me.\t04\tNot now, sorry.\t08",
        "04\tUpdate.Attribute\tEscortQuest\t=1",
        "05\tFollow.Player\tGranny_Wren\tON",
        "06\tDisplay.Message\tYellow\tQuest started: %s. (H: your journal)\tQuest" % QUEST,
        "07\tEnd",
        "08\tEnd",
        "09\t>Conditional\t$Variable.1=1\t17",
        "10\t>On.Map\t2,3,0\t14",
        "11\t>Distance.From.Coordinates\t%s\t%d\t14" % (px(DOOR), NEAR),
        "12\tGoto.Script\tGranny Wren Home",
        "13\tEnd",
        "14\tFollow.Player\tGranny_Wren\tON",
        "15\tDisplay.Conversation\tOld_Woman\tLead on, dear. I'm right behind you - just not very quickly.\tOff we "
