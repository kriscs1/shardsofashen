"""Getting about the bigger world, and finding your way in it.

Not run on its own: build_content.extend() calls extend() here after build_regions (so the towns exist) and before the
scenery pass (so no rock is put on a shardstone).

  * SHARDSTONES (fast travel): one in each town. Touching one ("Travel") attunes you to it the first time (attribute
    Shardstone.<Key> = 1) and opens the travel menu; a shardstone you haven't been to yet can't be travelled to. The menu is
    pages of three places (conversation answers), with "More..." to the next page.
  * QUEST MARKERS: Quests.ini Marker<N>=<place>[;<place>...]: where to go while the quest's
    attribute is N. The game shows a yellow mark on the minimap for each quest in progress (when that map is on the
    level you're on), unless Config [Gameplay] QuestMarkers=0. Each is a named place (build_places.py: an Id line on
    its map), so a marker never points at stale coordinates.
  * AMBIENCE: data\\Ambient.ini [Maps] <map>=<sound>: the background loop played on each map (sounds\\Ambient_<sound>.wav,
    made by build_sounds.py). Worked out from the map: caves, the Wildlands' lands, sea coasts and woods.
"""
import os
