class World:
    def __init__(self):
        self.maps = {}

    def get_map(self, mx, my, make=None):
        n = "%d,%d,0" % (mx, my)
        if n not in self.maps:
            if os.path.exists(p("maps", n + ".txt")):
                self.maps[n] = Map(n)
            elif make:
                self.maps[n] = Map(n, new=True)
                self.maps[n].rows = [[make] * XT for _ in range(YT)]
            else:
                return None
        return self.maps[n]

    def cell(self, gx, gy):
        m = self.get_map(gx // XT, gy // YT)
        return m.rows[gy % YT][gx % XT] if m else None

    def put(self, gx, gy, text, make=None):
        m = self.get_map(gx // XT, gy // YT, make)
        if m:
            m.rows[gy % YT][gx % XT] = text

    def line(self, gx, gy, kind, name, opts="", make=None):
        m = self.get_map(gx // XT, gy // YT, make)
        if m:
            m.ents.append(obj_line(kind, name, gx % XT + 1, gy % YT + 1, opts, dy=-8 if kind == "NPC" else 0))

    def place_id(self, gx, gy, name):
        m = self.get_map(gx // XT, gy // YT)
        if m:
            m.ents.append("Id\t%s\t%d\t%d" % (name, gx % XT + 1, gy % YT + 1))

    def save(self):
        for m in self.maps.values():
            m.save()


def noise_radius(angle, seed):
    r = random.Random(seed)
    ph = [r.uniform(0, 6.28) for _ in range(5)]
    return 1 + 0.18 * math.sin(2 * angle + ph[0]) + 0.13 * math.sin(3 * angle + ph[1]) + 0.08 * math.sin(5 * angle + ph[2]) + \
        0.05 * math.sin(7 * angle + ph[3]) + 0.04 * math.sin(11 * angle + ph[4])


def ring_of(cx, cy, rx, ry, seed):
    """Cells of a natural blob, never an ellipse's clean edge: its radius wandering with the angle."""
    for gy in range(int(cy - ry * 1.5), int(cy + ry * 1.5)):
        for gx in range(int(cx - rx * 1.5), int(cx + rx * 1.5)):
            dx, dy = (gx - cx) / rx, (gy - cy) / ry
            if math.hypot(dx, dy) <= noise_radius(math.atan2(dy, dx), seed):
                yield gx, gy


def occupied(world):
    """The cells with a line on them, on every map read."""
    out = set()
    for n, m in world.maps.items():
        mx, my, _ = W.mxyz(n)
        for ln in m.ents:
            c = W.line_cell(ln, mx, my)
            if c:
                out.add(c)
    return out


