def east_town(t, dx=-2, dy=-2):
    import build_eastreach as E
    cx, cy = E.town_centre(t)
    return PL.marker(t + "_Square", "%s %d %d" % E.local(cx + dx, cy + dy))


def east_site(s, dy=0):
    import build_eastreach as E
    sx, sy = E.SITES[s]
    return PL.marker(site_name(s), "%s %d %d" % E.local(sx, sy + dy))


def add_markers():
    marks = quest_markers()
    for name, keys in C.QUESTS:
        for stage, where in sorted(marks.get(name, {}).items()):
            key = "Marker%d" % stage
            if not any(k == key for k, _ in keys):
                keys.append((key, where))


# ------------------------------------------------------------------ ambience
AMBIENT_LANDS = {"wood": "Forest", "moor": "Wind", "marsh": "Marsh", "hills": "Wind", "desert": "Desert", "snow": "Snow"}


def ambient_for(name):
    x, y, z = (int(v) for v in name.split(","))
    if name == "0,0,-9":
        return "Lair"
    if z < 0:
        return "Cave"
    if z > 0:
        return "Indoors"
    if R.MX0 <= x <= R.MX1 and R.MY0 <= y <= R.MY1:
        return AMBIENT_LANDS[R.land_of(x * R.GW + 12, y * R.GH + 10)]
    import build_eastreach as E
    if E.MX0 <= x <= E.MX1 and E.MY0 <= y <= E.MY1:
        return {"elder": "Forest", "downs": "Wind"}[E.land_of(x * E.GW + 12, y * E.GH + 10)]
    import build_cinder as CI
    if CI.MX0 <= x <= CI.MX1 and CI.MY0 <= y <= CI.MY1:
        return {"ash": "Wind", "cinder": "Desert"}[CI.land_of(x * CI.GW + 12, y * CI.GH + 10)]
    cells = W.load_cells(name) or []
    water = sum(1 for row in cells for t in row if t.startswith("Water") or t.startswith("Sea_Rock"))
    return "" if water > 140 else "Forest"     # Seaside maps are quiet (the waves were heard all over them)


SEA_TILES = 100        # a surface map with more water than this is by the sea: no background sound (it sounded like surf)


def by_the_sea(name):
    if not name.endswith(",0"):
        return False
    cells = W.load_cells(name) or []
    return sum(1 for row in cells for t in row if t.startswith(("Water", "Sea_Rock", "Sand_Water", "Snow_Water"))) > SEA_TILES


def write_ambient():
    from common import p, write_lines
    lines = ["; Background sound for each map: sounds\\Ambient_<name>.wav, looped while you're on that map (Config [Sounds]",
             "; Ambient=0 turns them off). Generated by dev\\migrate\\build_travel.py: edit it there.", "", "[Maps]"]
    for name in W.all_maps():
        sound = ambient_for(name)
        if sound and not by_the_sea(name):
            lines.append("%s=%s" % (name, sound))
    return ["data\\Ambient.ini"] if write_lines(p("data", "Ambient.ini"), lines) else []


# ------------------------------------------------------------------ hook
def extend(world, content, regions):
    global W, C, R
    W, C, R = world, content, regions
    spots = town_spots()
    for k, (label, m, (sx, sy), _) in spots.items():
        if m in W.MAPS and m not in W.PROTECTED_MAPS:
            W.MAPS[m]["entities"].append(W.obj("Shardstone", sx, sy))
    C.ENTITIES["Shardstone"] = C.station("Travel", "An ancient shardstone carved with a glowing rune. Touch it to travel to any shardstone you have found.")
    W.S["Travel Shardstone"], W.S["Shardstone Menu"] = travel_script(spots)
    W.EXTRA_STEPS.append(write_ambient)
