def commands():
    """{name: [argument types]} (the first of a name wins)."""
    out = {}
    for name, args in COMMANDS:
        out.setdefault(name, args)
    return out


def help_for(item):
    """The help for a command or argument type ("" if none; spaces round the name don't matter)."""
    if item in HELP:
        return HELP[item]
    want = item.strip()
    return next((v for k, v in HELP.items() if k.strip() == want), "")
