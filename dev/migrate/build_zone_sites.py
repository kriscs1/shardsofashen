def relay_rime(world, rng):
    """Its old ground off (the coast it was laid over as it was), and a big island of snow in its place: frozen lakes, pine
    woods, ridges, rocky ground; inside its maps, so no edge of it is cut straight."""
    x1, x2, y1, y2 = RIME
    kept = []
    for mx in range(x1, x2 + 1):
        for my in range(y1, y2 + 1):
            m = world.get_map(mx, my, make="Water001")
            old = committed(m.name)
            for y in range(YT):
                for x in range(XT):
                    c = m.rows[y][x]
                    b = c.split("+")[0]
                    if old is not None:
                        ob = old[y][x].split("+")[0]
                        if b in ("Snow001", "Ice001") and ob != b and not W.WATERY.match(ob) and not W.PEAKY.match(ob):
                            m.rows[y][x] = old[y][x]              # (the coast as it was before; a pass cut stays cut)
                        elif b in ("Snow001", "Ice001") and W.WATERY.match(ob):
                            m.rows[y][x] = "Water001"
                    elif not W.WATERY.match(b):
                        m.rows[y][x] = "Water001"
            keep = []
            for ln in m.ents:
                f = ln.split("\t")
                if f[0] == "NPC" and f[1] in RIME_MOBS and "Id=" not in ln:
                    continue                                    # (its monsters: placed again below)
                if "Id=" in ln or f[0] == "Id":
                    kept.append((m, ln))
                keep.append(ln)
            m.ents = keep
    cx, cy, rx, ry = 18.8 * XT, 26.9 * YT, 94, 51
    land = set()
    for gx, gy in Z.ring_of(cx, cy, rx, ry, 29):
        c = world.cell(gx, gy)
        if c is not None and W.WATERY.match(c.split("+")[0]) and gy >= y1 * YT + 3:
            world.put(gx, gy, "Snow001")
            land.add((gx, gy))
    # (what's in it: lakes frozen over, ridges, pine woods, rocky ground)
    def blob(rxr, ryr, seed, near=None):
        cells = list(land)
        for _ in range(400):
            bx, by = rng.choice(cells)
            ok = all((bx + int(rxr * 1.5 * math.cos(a)), by + int(ryr * 1.5 * math.sin(a))) in land for a in (0, 1.6, 3.1, 4.7))
            if ok:
                return [c for c in Z.ring_of(bx, by, rxr, ryr, seed) if c in land]
        return []
    for k in range(4):
        for c in blob(rng.randint(6, 10), rng.randint(4, 7), 300 + k):
            world.put(c[0], c[1], "Ice001")
    for k in range(5):
        for c in blob(rng.randint(7, 12), rng.randint(2, 3), 320 + k):
            if world.cell(*c) == "Snow001":
                world.put(c[0], c[1], "Snow_Peak001")
    for k in range(5):
        for c in blob(rng.randint(7, 11), rng.randint(5, 8), 340 + k):
            if world.cell(*c) == "Snow001" and rng.random() < 0.32:
                world.put(c[0], c[1], "Snow001+Decor(Snow_Pine001)")
    for k in range(3):
        for c in blob(rng.randint(5, 8), rng.randint(4, 6), 360 + k):
            if world.cell(*c) == "Snow001" and rng.random() < 0.08:
                world.put(c[0], c[1], "Snow001+Decor(Snow_Rock001)")
    for gx, gy in land:
        if world.cell(gx, gy) == "Snow001":
            r = rng.random()
            if r < 0.025:
                world.put(gx, gy, "Snow001+Decor(Snow_Pine001)")
            elif r < 0.035:
                world.put(gx, gy, "Snow001+Decor(Snow_Rock001)")
    for _ in range(3):                                          # (mithril, in clusters)
        bx, by = rng.choice(sorted(land))
        for _ in range(5):
            gx, gy = bx + rng.randint(-2, 2), by + rng.randint(-2, 2)
            if world.cell(gx, gy) == "Snow001":
                world.put(gx, gy, "Snow001+Decor(Mithril_Rock001)")
    # (the frozen strait from the north shore, down to it wherever it is now)
    x, y = 18 * XT + 12, 22 * YT + 6
    while y < y2 * YT:
        c = world.cell(x, y)
        if c is None:
            break
        if (x, y) in land and not W.WATERY.match(c.split("+")[0]):
            break
        for k in (-2, -1, 0, 1, 2):
            cc = world.cell(x + k, y)
            if cc and W.WATERY.match(cc.split("+")[0]):
                world.put(x + k, y, "Ice001")
        y += 1
    for m, ln in kept:                                           # (those with names: on the land again, if not)
        cell = W.line_cell(ln, *W.mxyz(m.name)[:2])
