def numbered(lines):
    """Script lines run on in order: a number nothing jumps to, and nothing runs into, is an End."""
    have = {int(ln[:2]): ln for ln in lines}
    return [have.get(k, "%02d\tEnd" % k) for k in range(1, max(have) + 1)]


def write_scripts():
    for name, lines in SCRIPTS.items():
        with open(p("data", "Scripts", name + ".script"), "wb") as f:
            f.write(("\r\n".join([MAKER] + numbered(lines)) + "\r\n").encode("cp1252"))


