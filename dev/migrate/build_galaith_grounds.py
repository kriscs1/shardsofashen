def pool_water(piece, frame):
    """The water of a piece: deep and clear, little rings and glints that move (inside the tile: no seam between)."""
    rng = random.Random("pool" + piece)
    im = new()
    px = im.load()
    bottom = FLOOR if piece in ("BL", "B", "BR") else S
    for y in range(bottom):
        for x in range(S):
            k = rng.random()
            c = WATER if k < 0.55 else WATER_DEEP if k < 0.9 else shade(WATER, 1.08)
            px[x, y] = c + (255,)
    for _ in range(3 if piece == "M" else 1):                  # (the coins on the bottom)
        cx, cy = rng.randrange(6, 26), rng.randrange(4, max(5, bottom - 3))
        px[cx, cy] = (224, 186, 84, 255)
        px[cx + 1, cy] = (168, 132, 52, 255)
    d = ImageDraw.Draw(im)
    rings = random.Random("rings" + piece)
    for k in range(4):
        x0, y0 = rings.randrange(6, 24), rings.randrange(3, max(4, bottom - 3))
        t = (frame + k) % 4
        if t < 3:                                              # (a ripple widening, then gone)
            r = 1 + t
            d.arc((x0 - r * 2, y0 - r, x0 + r * 2, y0 + r), 200, 340, fill=WATER_LIT if t == 0 else shade(WATER_LIT, 0.82))
    return im


def pool_rim(im, piece):
    """The rim standing up round the water: pale coping, its shadow falling on the water inside, a carved joint now and
    then, and along the front the rim's face going down to the paving. Its outer corners are rounded off."""
    d = ImageDraw.Draw(im)
    top, left, right, front = piece[0] == "T", "L" in piece, "R" in piece, piece[0] == "B"
    y0 = FLOOR if front else 0
    if top:                                                    # (the water just inside it, in its shadow)
        d.rectangle((0, RIM_W, S, RIM_W + 2), fill=shade(WATER_DEEP, 0.6))
    if left:
        d.rectangle((RIM_W, 0, RIM_W + 2, FLOOR if front else S), fill=shade(WATER_DEEP, 0.6))
    if right:
        d.rectangle((S - RIM_W - 1, 0, S - RIM_W, FLOOR if front else S), fill=shade(WATER_DEEP, 0.75))
    if top:
        d.rectangle((0, 0, S, RIM_W - 1), fill=RIM)
        d.line((0, 0, S, 0), fill=RIM_LIT)
        d.line((0, RIM_W - 1, S, RIM_W - 1), fill=RIM_DARK)
    if front:
        d.rectangle((0, y0, S, y0 + RIM_W - 1), fill=RIM)
        d.line((0, y0, S, y0), fill=RIM_LIT)
        d.line((0, y0 + RIM_W - 1, S, y0 + RIM_W - 1), fill=RIM_DARK)
        d.rectangle((0, y0 + RIM_W, S, S - 1), fill=FACE)      # (the face: it's raised, and you can see how much)
        d.line((0, y0 + RIM_W + 2, S, y0 + RIM_W + 2), fill=FACE_DARK)
        d.line((0, S - 1, S, S - 1), fill=shade(FACE_DARK, 0.7))
    if left:
        d.rectangle((0, 0, RIM_W - 1, S if not front else y0 + RIM_W - 1), fill=RIM)
        d.line((0, 0, 0, S), fill=RIM_LIT)
        d.line((RIM_W - 1, RIM_W if top else 0, RIM_W - 1, y0 if front else S), fill=RIM_DARK)
        if front:
            d.rectangle((0, y0 + RIM_W, S if not right else RIM_W - 1, S - 1), fill=FACE)
    if right:
        d.rectangle((S - RIM_W, 0, S - 1, S if not front else y0 + RIM_W - 1), fill=RIM)
        d.line((S - 1, 0, S - 1, S), fill=RIM_DARK)
        d.line((S - RIM_W, RIM_W if top else 0, S - RIM_W, y0 if front else S), fill=RIM_LIT)
    for k in (9, 25):                                          # (the coping's joints)
        if top or front:
            yy = 0 if top else y0
            d.line((k, yy + 1, k, yy + RIM_W - 2), fill=RIM_DARK)
        if (left or right) and not (top and k < RIM_W) and not (front and k > y0):
            xx = 0 if left else S - RIM_W
            d.line((xx + 1, k, xx + RIM_W - 2, k), fill=RIM_DARK)
    px = im.load()
    for corner, on in (((0, 0, 1, 1), piece == "TL"), ((S - 1, 0, -1, 1), piece == "TR"),
                       ((0, S - 1, 1, -1), piece == "BL"), ((S - 1, S - 1, -1, -1), piece == "BR")):
        if on:
            cx, cy, sx, sy = corner
            for a in range(3):
                for b in range(3 - a):
                    px[cx + sx * a, cy + sy * b] = (0, 0, 0, 0)
    return im


