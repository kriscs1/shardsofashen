def cell_parts(atlas, c):
    m, x, y = atlas.at(*c)
    return (None, {}) if m is None else m.parts(x, y)


def inside_walls(atlas):
    """Every cell inside the outer walls, by walking out from the avenue and from the palace's gate until a wall stops
    it (the gates shut, for this)."""
    shut = {(x, y) for x in (AVENUE_X, AVENUE_X + 1) for y in (NORTH, NORTH + 1, SOUTH, SOUTH + 1)}
    seen, todo = set(), [(AVENUE_X, 320), (-245, 290)]
    while todo:
        c = todo.pop()
        if c in seen or c in shut:
            continue
        t, _ = cell_parts(atlas, c)
        if t is None or re.match(r"(Galaith_Wall|Burnt_Wall|Burnt_Gate|Galaith_Gate)", t):
            continue
        if not (WEST <= c[0] <= EAST and NORTH <= c[1] <= SOUTH):
            raise SystemExit("Walked out of the city at %d,%d: a gap in its wall?" % c)
        seen.add(c)
        todo.extend((c[0] + dx, c[1] + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
    return seen


def in_box(c, box):
    return box[0] <= c[0] <= box[2] and box[1] <= c[1] <= box[3]


def quarter(c):
    if in_box(c, ROYAL):
        return "Royal"
    if NOBLES_WEST <= c[0] <= NOBLES_EAST and c[1] <= NOBLES_SOUTH:
        return "Nobles"
    return "Town"


GROUND = {"Royal": "Royal_Paving001", "Nobles": "Noble_Paving001", "Town": "Flagstone001"}
STREET = {"Royal": "Marble_Paving001", "Nobles": "Marble_Paving001", "Town": "Cobble001"}
KEEP_TREE = {"Royal": 0.34, "Nobles": 0.3, "Town": 0.14}
TREES = re.compile(r"^(Tree|Oak_Tree)\d")
SOFT = re.compile(r"^(Flowers|Bush|Rock)\d")


def pave(atlas, inside):
    """Grass to paving and dirt to street, in every open cell inside the walls; what grew on the grass thinned out."""
    plots = (COURT, GRAVEYARD, ORCHARD)
    made = {"Royal": 0, "Nobles": 0, "Town": 0}
    for c in sorted(inside):
        m, x, y = atlas.at(*c)
        t, over = m.parts(x, y)
        if over.get("Roof") or t not in ("Grass001", "Dirt001"):
            continue
        q = quarter(c)
        made[q] += 1
        d = over.get("Decor", "")
        if TREES.match(d):
            near_road = any(cell_parts(atlas, (c[0] + dx, c[1] + dy))[0] in ("Dirt001", "Cobble001", "Marble_Paving001")
                            for dx in (-1, 0, 1) for dy in (-1, 0, 1))
            if near_road or h01("keep tree", *c) >= KEEP_TREE[q] or any(in_box(c, b) for b in plots):
                over.pop("Decor")
            else:
                over["Under"] = "Tree_Pit001"
        elif SOFT.match(d):
            over.pop("Decor")
            r = h01("urn", *c)
            if q != "Town" and d.startswith("Flowers") and r < 0.14:
                over["Decor"] = "Flower_Urn001"
            elif q == "Town" and d.startswith("Flowers") and r < 0.07:
                over["Decor"] = "Potted_Plant00%d" % (1 + int(r * 1000) % 3)
        m.put(x, y, (GROUND if t == "Grass001" else STREET)[q], over)
    return made


def lamps(atlas, inside):
    """Lamps along the avenues, either side, every so often."""
    spots = [(x, 303 if k % 2 else 306) for k, x in enumerate(range(-221, -112, 11))]
    spots += [(AVENUE_X - 2 if k % 2 else AVENUE_X + 3, y) for k, y in enumerate(range(268, 380, 11))]
    n_lamps = 0
    for c in spots:
        if c not in inside:
            continue
        m, x, y = atlas.at(*c)
        t, over = m.parts(x, y)
        if not over.get("Decor") and not over.get("Roof") and t in GROUND.values():
            over["Decor"] = "Lamp_Post001"
            m.put(x, y, t, over)
            n_lamps += 1
    return n_lamps


def put(atlas, c, tile_name=None, decor=None, under=None):
    m, x, y = atlas.at(*c)
    t, over = m.parts(x, y)
    if decor is not None:
        over.pop("Decor", None)
        if decor:
            over["Decor"] = decor
    if under is not None:
        over.pop("Under", None)
        if under:
            over["Under"] = under
    m.put(x, y, tile_name or t, over)


def box_cells(box):
    return [(x, y) for y in range(box[1], box[3] + 1) for x in range(box[0], box[2] + 1)]


