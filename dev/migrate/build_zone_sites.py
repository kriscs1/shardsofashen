def free_cell(world, gx, gy, taken, allow):
    c = world.cell(gx, gy)
    if c is None or (gx, gy) in taken:
        return False
    bits = c.split("+")
    if not allow.match(bits[0]):
        return False
    return all(b.startswith("Decor(") and W.WILD_DECOR.match(b[6:-1]) for b in bits[1:])


def find_site(world, cells, rng, taken, sites, w=18, h=13):
    cells = sorted(cells)
    allow = re.compile(r"^(%s)" % "|".join(sorted({re.sub(r"\d+$", "", world.cell(*c).split("+")[0]) for c in cells[::7]
                                                    if world.cell(*c)})))
    for _ in range(4000):
        cx, cy = rng.choice(cells)
        gx, gy = cx - w // 2, cy - h // 2
        if gx // XT != (gx + w - 1) // XT or gy // YT != (gy + h - 1) // YT:
            continue
        if any(abs(cx - a) + abs(cy - b) < 34 for a, b in sites):
            continue
        if all(free_cell(world, x, y, taken, allow) for y in range(gy, gy + h) for x in range(gx, gx + w)):
            return cx, cy, gx, gy
    return None


def pick(pairs, rng):
    total = sum(w for _, w in pairs)
    r = rng.uniform(0, total)
    for name, w in pairs:
        r -= w
        if r <= 0:
            return name
    return pairs[-1][0]


