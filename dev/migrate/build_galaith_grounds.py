def royal_texture(rng, size=128, per=3):
    """Lozenges of ivory and rose marble, a line of gold between: the pattern's period isn't the tiles', so no grid."""
    ys, xs = np.mgrid[0:size, 0:size].astype(np.float64)
    period = size / float(per)
    u, v = (xs + ys) / period, (xs - ys) / period
    check = (np.floor(u) + np.floor(v)) % 2
    veins = np.abs(fractal(rng, size, 4, ridged=True, cells=6) - 0.5)
    col = np.where(check[..., None] > 0, np.array((226, 196, 186.0)), np.array((240, 234, 222.0)))
    col = col - (fractal(rng, size, 3, cells=4)[..., None] - 0.5) * 18
    col = col * (1 - (np.clip(0.035 - veins, 0, 1) / 0.035)[..., None] * 0.16)
    edge = np.minimum(np.abs(u - np.round(u)), np.abs(v - np.round(v))) * period / math.sqrt(2)
    lit = np.clip((3.0 - edge) / 3.0, 0, 1)[..., None]
    col = col * (1 - lit * 0.1)
    gold = np.clip((1.05 - edge) / 0.7, 0, 1)[..., None]
    return np.clip(col * (1 - gold) + np.array((190, 152, 78.0)) * gold, 0, 255).astype(np.uint8)


def noble_texture(rng, size=128):
    """Dressed limestone in courses, cream and honey, tight joints: smoother than the flags, and laid straight."""
    return rows_of_stones(rng, size, (14, 16, 18), (18, 22, 26, 30, 34),
                          [(216, 202, 174), (206, 192, 162), (224, 212, 186), (198, 186, 158)], (146, 130, 104),
                          bevel=8, crack=0.03)


def lawn_texture(rng, size=128, stripes=4):
    """Short grass, mown on the slant: paler and darker strips, no tile's edge in them."""
    ys, xs = np.mgrid[0:size, 0:size].astype(np.float64)
    band = np.sin((xs + ys) * math.pi * stripes * 2 / size)
    col = np.array((76, 110, 34.0)) + np.clip(band * 3, -1, 1)[..., None] * np.array((5, 8, 2.0))
    col = col + (fractal(rng, size, 2, cells=64)[..., None] - 0.5) * np.array((26, 34, 16.0))
    col = col + (fractal(rng, size, 3, cells=5)[..., None] - 0.5) * 12
    return np.clip(col, 0, 255).astype(np.uint8)


