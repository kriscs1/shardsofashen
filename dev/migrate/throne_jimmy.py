"""Jimmy in the throne room (12,5,0, once you're king) is Jimmy the cat, not a picture of him: he wanders the hall,
sits, stretches, turns his back on you, and now and then hops up onto the throne and curls up asleep on it (Nap=13,7)
if nobody's sitting there. The throne is a seat now (Seat=S), and if you sit on it he hops down. The old still
picture (Throne_Jimmy) is gone; Throne_Jimmy is his Id. A second run does nothing.

  python -I "dev\\migrate\\throne_jimmy.py"
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)
from ashen import ini  # noqa: E402
from build_isle import DATA  # noqa: E402

JIMMY = "Strawberry_Cat\tNPC\tAttitude=Good Zone=6,8,20,12 Nap=13,7 Pause=4-12 Id=Throne_Jimmy Name=Jimmy"


def write(name, lines):
    with open(os.path.join(DATA, "Scripts", name + ".txt"), "w", encoding="cp1252", newline="\r\n") as f:
        f.write("// Generated by dev\\migrate\\build_heir_mainland.py\n" + "\n".join(lines) + "\n")


def main():
    n = 0
    tiles = os.path.join(DATA, "Tiles.ini")
    for k, v in (("Use.Words", "Sit"), ("Seat", "S")):
        if ini.read("Throne001", k, "", tiles) != v:
            ini.write("Throne001", k, v, tiles)
            n += 1
    for name in ("12,5,0", "Talk to Rupert_On_Throne"):
        path = os.path.join(DATA, "Scripts", name + ".txt")
        with open(path, "rb") as f:
            text = f.read().decode("cp1252")
        new = text.replace("Throne_Jimmy\tStaticObject\t-", JIMMY).replace("384,178\t" + JIMMY, "384,190\t" + JIMMY)
        # (a little lower than the old picture: on the cushion)
        if new != text:
            with open(path, "wb") as f:
                f.write(new.encode("cp1252"))
            n += 1
    write("Stroke Throne_Jimmy", [
        "01\t>Entity.State\tCLICKED\tCurl\t05",
        "02\tPlay.Sound\tPurr",
        "03\tDisplay.Message\tCyan\tJimmy purrs, stretches across the throne, and goes back to sleep. He's the king of "
        "this, really.",
        "04\tEnd",
        "05\tPlay.Sound\tPurr",
        "06\tDisplay.Message\tCyan\tJimmy purrs like a little engine and headbutts your hand for more.",
        "07\tEnd"])
    write("Talk to Throne_Jimmy", [
        "01\tPlay.Sound\tMeow",
        "02\tDisplay.Message\tCyan\tJimmy looks up at you and gives a little chirp, very pleased with himself.",
        "03\tEnd"])
    ents = os.path.join(DATA, "Entities.ini")
    if ini.section("Throne_Jimmy", ents):
        with open(ents, "rb") as f:
            text = f.read().decode("cp1252")
        nl = "\r\n" if "\r\n" in text else "\n"
        out, skip = [], False
        for ln in text.split(nl):
            if ln.startswith("["):
                skip = ln.strip() == "[Throne_Jimmy]"
            if not skip:
                out.append(ln)
        with open(ents, "wb") as f:
            f.write(nl.join(out).encode("cp1252"))
        n += 1
    pic = os.path.join(ROOT, "sprites", "Entities", "Throne_Jimmy.png")
    if os.path.exists(pic):
        os.remove(pic)
        n += 1
    print("Jimmy on the throne is the cat himself (%d changes)" % n if n else "Jimmy's himself on the throne already")


if __name__ == "__main__":
    main()
