def fountain_water(count):
    """Water falling from bowl to bowl, on and on: soft rushing noise, and the small plashes in it."""
    base = lowpass(noise(11, count, 0.22), 0.3)
    rng = random.Random("fountain")
    out = [v * (0.75 + 0.1 * math.sin(i * 2 * math.pi / 19000)) for i, v in enumerate(base)]
    for _ in range(int(count / 2600)):
        f = rng.uniform(320, 720)
        at = rng.randrange(0, max(1, count - n(0.1)))
        plash = shaped(tone(f, n(0.09), glide=0.5), 0.002, 40)
        g = rng.uniform(0.06, 0.16)
        for k, v in enumerate(plash):
            out[at + k] += v * g
    return out


def coin_splash():
    """A coin spun off a thumb: a small low ring, then the plop, and the water closing over it."""
    return mix((shaped(bell(880, 0.25, 7), 0.002, 14), 0.5),
               (delay(shaped(tone(280, n(0.14), glide=1.1), 0.002, 22), 0.33), 0.8),
               (delay(shaped(noise(4, n(0.3), 0.18), 0.01, 11), 0.33), 0.5))


def sounds():
    for name, sig, level in (("Ambient_Fountain", loop_of(fountain_water), 0.32), ("Coin_Splash", coin_splash(), 0.7)):
        path = p("sounds", name + ".wav")
        blob = wav_bytes(sig, level)
        if not os.path.exists(path) or open(path, "rb").read() != blob:
            with open(path, "wb") as f:
                f.write(blob)


