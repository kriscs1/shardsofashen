def house(world, gx, gy, w, h, wall, roof, kind, rng):
    """A building on one map, gx, gy its top left: walls, roof, a door in the middle of its front, things in it. Returns the
    cells of its floor (for a chest)."""
    m = world.get_map(gx // XT, gy // YT)
    x1, y1 = gx % XT + 1, gy % YT + 1
    x2, y2 = x1 + w - 1, y1 + h - 1
    door = x1 + w // 2
    K.building(m, x1, y1, x2, y2, door, wall=wall, roof=roof)
    floor = [(x, y) for y in range(y1, y2) for x in range(x1 + 1, x2)]
    keep_clear = {(door, y2 - 1), (door, y2 - 2)}
    for name, where, dx in FURNISH.get(kind, []):
        if where == "back":
            x, y = (x1 + 1 + dx) if dx > 0 else (x2 - 1 + dx + 1) if dx < 0 else (x1 + x2) // 2, y1
        elif where == "mid":
            x, y = (x1 + x2) // 2 + dx, (y1 + y2) // 2
        else:
            x, y = x2 - 1, y2 - 1
        if not (x1 < x < x2 and y1 <= y < y2) or (x, y) in keep_clear or m.decor(x, y):
            continue
        if name == "Bed001":
            if y + 1 >= y2 or m.decor(x, y + 1) or (x, y + 1) in keep_clear:
                continue
            m.set(x, y + 1, decor="Bed002")
        m.set(x, y, decor=name)
    return [(gx + x - x1, gy + y - y1) for x, y in floor if not m.decor(x, y) and (x, y) not in keep_clear and y > y1]


def build_site(world, site, spot, rng, taken, zone_cells):
    cx, cy, gx, gy = spot
    rx, ry = site["r"]
    allow_into = set(zone_cells)
    patch = [c for c in Z.ring_of(cx, cy, rx, ry, sum(map(ord, site["id"])) % 997) if (c in allow_into or
             (gx <= c[0] < gx + 15 and gy <= c[1] < gy + 11)) and free_cell(world, c[0], c[1], taken, OPEN_GROUND)]
    for x, y in patch:                                          # (its own ground, then what lies about on it)
        t = pick(site["ground"], rng)
        d = ""
        if site.get("decor") and rng.random() * 100 < site.get("dens", 5):
            d = "+Decor(%s)" % pick(site["decor"], rng)
        world.put(x, y, t + d)
    if site.get("pools"):                                       # (lava, a cave pool: a pool or two in it)
        for k in range(2):
            px, py = rng.choice(patch)
            for c in Z.ring_of(px, py, rng.randint(2, 3), rng.randint(1, 2), k + 7):
                if c in set(patch) and abs(c[0] - cx) + abs(c[1] - cy) > 5:
                    world.put(c[0], c[1], site["pools"])
                    taken.add(c)
    if site.get("mesas"):                                       # (rock standing up out of it)
        for k in range(site["mesas"]):
            a = rng.uniform(0, 6.28)
            px, py = int(cx + math.cos(a) * rx * 0.8), int(cy + math.sin(a) * ry * 0.8)
            for c in Z.ring_of(px, py, rng.randint(2, 4), rng.randint(1, 2), k + 11):
                if c in set(patch) and abs(c[0] - cx) + abs(c[1] - cy) > 6:
                    world.put(c[0], c[1], site.get("mesa", "Mountain001"))
                    taken.add(c)
    if site.get("ring"):                                        # (a hollow: ridges round it, a way in on the south)
        for a in range(0, 360, 6):
            if 70 < a < 110:
                continue
            x, y = int(cx + math.cos(math.radians(a)) * rx), int(cy + math.sin(math.radians(a)) * ry)
            for c in ((x, y), (x + 1, y)):
                if c in set(patch):
                    world.put(c[0], c[1], site["ring"])
                    taken.add(c)
    # (its buildings: in the middle of it, side by side, each on its own map with room before its door)
    rooms = []
    hx = gx + 1
    for w, h, wall, roof, kind in site.get("houses", []):
        hy = cy - h // 2
        if hx + w >= gx + 16 or hx // XT != (hx + w - 1) // XT or hy // YT != (hy + h) // YT:
            continue
        for y in range(hy, hy + h + 2):
            for x in range(hx - 1, hx + w + 1):
                if world.cell(x, y):
                    world.put(x, y, site["ground"][0][0])
        rooms.append(house(world, hx, hy, w, h, wall, roof, kind, rng))
        for y in range(hy, hy + h + 2):
            for x in range(hx - 1, hx + w + 1):
                taken.add((x, y))
        hx += w + 2
    open_ = [c for c in patch if c not in taken and "+" not in (world.cell(*c) or "+")]
    rng.shuffle(open_)
    for name, n in site.get("things", []):
        for _ in range(n):
            if not open_:
                break
            x, y = open_.pop()
            world.put(x, y, world.cell(x, y) + "+Decor(%s)" % name)
            taken.add((x, y))
    if site.get("chest") and rooms and rooms[0]:
        x, y = rooms[0][len(rooms[0]) // 2]
        moved = move_line(world, "Id=Zone_Chest_%s" % site["zone"], x, y)
        if not moved:
            world.line(x, y, "StaticObject", "Chest", "Id=Zone_Chest_%s" % site["zone"])
        taken.add((x, y))
    who = []
    if site.get("giver"):
        who.append((site["giver"], None))
    who += site.get("folk", [])
    for kind, name in who:
        if not open_:
            break
        x, y = open_.pop()
        lx, ly = x % XT + 1, y % YT + 1
        zone = "Zone=%d,%d,%d,%d" % (max(1, lx - 3), max(1, ly - 2), min(XT, lx + 3), min(YT, ly + 2))
        if name is None:                                         # (a quest giver: moved here, Id and all)
            if not move_line(world, "Id=%s" % kind, x, y, extra=zone):
                print("No", kind, "to move")
        else:
            sprite = kind
            world.line(x, y, "NPC", sprite, "Attitude=Good Schedule=Always %s Id=%s Name=%s" % (zone, name, name))
            write_folk(name, sprite, site)
        taken.add((x, y))
    group = "Group=%s" % site["id"] if site.get("group") else ""
    away = [c for c in open_ if abs(c[0] - cx) + abs(c[1] - cy) > 7] if site.get("mobs_away") else open_
    for kind, n in site.get("mobs", []):
        for _ in range(n):
            if not away:
                break
            x, y = away.pop()
            if (x, y) in taken:
                continue
            Z.spawn(world, x, y, kind, taken, group)
    world.place_id(cx, cy + site["r"][1] // 2, site["id"])
    return len(patch)


def move_line(world, marker, gx, gy, extra=""):
    for m in list(world.maps.values()):
        for ln in list(m.ents):
            if marker in ln.split("\t")[-1].split() or ("\t" + marker) in ln:
                f = ln.split("\t")
                m.ents.remove(ln)
                opts = f[4] if len(f) > 4 else ""
                if extra:
                    opts = re.sub(r"\b(Stand|Zone|Face)=\S*", "", opts).strip() + " " + extra
                world.line(gx, gy, f[0], f[1], opts.strip())
                return True
    for path in glob.glob(p("maps", "*,0.txt")):              # (on a map not read yet)
        if marker.encode() in open(path, "rb").read():
            mx, my, _ = W.mxyz(os.path.basename(path)[:-4])
            world.get_map(mx, my)
            return move_line(world, marker, gx, gy, extra)
    return False


