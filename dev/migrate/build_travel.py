W = C = R = None        # build_world, build_content, build_regions


# Only a few shardstones, far apart, and none on the Isle: Ashford (the Southlands), Highwatch (the middle of the
# Wildlands), Dunerest (the desert's edge) and Thornwick (the Eastreach)
SHARDSTONES = ("Ashford", "Highwatch", "Dunerest", "Thornwick", "Emberwatch")


def town_spots():
    """Key -> (label, map, shardstone tile, arrival tile) for every shardstone."""
    return {k: v for k, v in all_spots().items() if k in SHARDSTONES}


def all_spots():
    """Key -> (label, map, shardstone tile, arrival tile) for every place that could have a shardstone."""
    out = {
        "Isle": ("The Isle", "1,1,0", (13, 11), (13, 12)),
        "Northport": ("Northport", "1,3,0", (16, 11), (13, 11)),
        "Ashford": ("Ashford", "2,3,0", (10, 13), (10, 12)),
        "Keep": ("Tyron's Keep", "2,4,0", (11, 19), (13, 20)),
    }
    import build_eastreach
    import build_walled
    import build_cinder
    for mod in (R, build_eastreach, build_walled, build_cinder):
        for town in mod.TOWNS:
            cx, cy = mod.town_centre(town)
            m, sx, sy = mod.local(cx - 2, cy + 2)
            _, ax, ay = mod.local(cx, cy + 2)
            out[town] = (town, m, (sx, sy), (ax, ay))
    return out


def short_name(label):
    """"The Isle" -> "Isle", so "the <name> shardstone" reads right."""
    return label[4:] if label.startswith("The ") else label


def travel_script(spots):
    """Touching a shardstone says which one it is (and attunes you to it the first time), then opens the menu: one
    conversation listing only the shardstones you have touched, other than this one (the Python game's [if ...] answers,
    up to 15 of them), and "Stay here"."""
    keys = list(spots)
    steps = ["// Shardstones: touching one tells you which it is (and attunes you to it the first time), then opens its",
             "// menu of the shardstones you have touched. Generated by build_travel.py",
             (">Distance.From.Clicked.Entity", "48", "@far")]
    for i, k in enumerate(keys):                    # which shardstone is this? its name, and attune to it
        label, m, _, _ = spots[k]
        steps += [(">On.Map", m, "@here%d" % (i + 1)),
                  ("Get.Value", "CALCULATION", short_name(label), "Variable.9$"),
                  (">Conditional", "$Attr.Waystone.%s=0" % k, "@menu"),
                  ("Update.Attribute", "Waystone." + k, "=1"),
                  ("Display.Message", "Yellow", "The rune flares blue: you are attuned to the %s shardstone." % short_name(label)),
                  ("Goto.Line", "@attuned"),
                  "here%d:" % (i + 1)]
    steps += [("Get.Value", "CALCULATION", "old", "Variable.9$"),       # a shardstone on a map not listed above
              ("Goto.Line", "@menu"),
              "attuned:", ("Play.Sound", "SpellCast"),                 # (one line for them all: scripts are <= 99)
              "menu:", ("Goto.Script", "Shardstone Menu"), ("End",)] + C.too_far()
    first = steps
    answers = []
    for k in keys:
        label, m, _, _ = spots[k]
        answers += ["%s [if $Attr.Waystone.%s>=1 and $Map.Name<>%s]" % (label, k, m), "@go_" + k]
    answers += ["Stay here", "@stay"]
    steps = ["// The shardstones' travel menu (Travel Shardstone comes here and sets $Variable.9 to this shardstone's name).",
             "// Each place only shows once you have touched its shardstone ([if ...]), and not the one you are at.",
             "// Generated by build_travel.py",
             ("Display.Conversation", "Shardstone",
              "This is the $Variable.9 shardstone. Its rune glows softly under your hand.\\Where would you like to go? "
              "(Only the shardstones you have touched are listed.)") + tuple(answers),
             "stay:", ("End",)]
    for k in keys:
        label, m, _, (ax, ay) = spots[k]
        steps += ["go_" + k + ":",
                  ("Play.Sound", "Teleporter"),
                  ("Display.Message", "Yellow", "The world blurs... and you step out by the %s shardstone." % short_name(label)),
                  ("Teleport", PL.tile("Waystone_" + k, m, ax, ay), "-"),
                  ("End",)]
    return first, steps


