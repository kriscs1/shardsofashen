"""Townsfolk of a kind who all say the same thing share one script (Code Issues 47). build_estforlan.py wrote every
barmaid, stall keeper, doctor... a Talk to <Id> of their own, word for word the same in town after town (36 of the 39
barmaids: "Sit anywhere you like, love"). Those copies go, and the words they share are written once as
Talk to <Kind>, which the game finds for any of that kind without words of their own (find_action_script: the Id's
script, then the kind's). One whose words differ keeps them, by its Id.

With no words of their own, the ones whose kind gossips (Entities.ini Gossip=1: Barmaid, the stalls, Doctor, Nurse,
Tailor) now and then pass on a rumour before their usual words (dsengine/rumours.py), as Rules.md has the trades do.

A kind is shared only when every one of it on the maps has words of its own today (nobody starts talking who didn't)
and it has no Talk to <Kind> yet. Run it again: it does nothing more (the copies are gone, the shared one stays).

  python -I "dev\\migrate\\share_npc_words.py"       (then validate.py)
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import story_kit as K  # noqa: E402

MAKER = "share_npc_words.py"
WROTE = "build_estforlan.py"            # (the builder whose copies these are: never run again)
KINDS = ("Barmaid", "Greengrocer", "Fishmonger", "Butcher", "Sheriff", "Doctor", "Nurse", "Tailor", "Armourer")
MAPS = os.path.join(K.ROOT, "maps")


def ids_of_kinds():
    """{kind: [its Id ("" for none), for each of that kind on a map]}"""
    out = collections.defaultdict(list)
    for fn in sorted(os.listdir(MAPS)):
        if not fn.endswith(".txt"):
            continue
        for line in open(os.path.join(MAPS, fn), "rb").read().decode("cp1252").replace("\r\n", "\n").split("\n"):
            p = line.split("\t")
            if len(p) > 4 and p[0] == "NPC" and p[1] in KINDS:
                m = re.search(r"\bId=(\S+)", p[4])
                out[p[1]].append(m.group(1) if m else "")
    return out


def script_path(name):
    return os.path.join(K.SCRIPTS, name + ".txt")


def main():
    shared = 0
    for kind, ids in sorted(ids_of_kinds().items()):
        mine = "Talk to " + kind
        if os.path.exists(script_path(mine)):
            continue                                        # (shared already, or a kind's words written by hand)
        if any(not i or not os.path.exists(script_path("Talk to " + i)) for i in ids):
            print("%-12s left: one has no words of its own (it would start saying the shared ones)" % kind)
            continue
        groups = collections.defaultdict(list)
        for i in ids:
            text = open(script_path("Talk to " + i), "rb").read()
            if text.split(b"\r\n")[0].decode("cp1252").strip().endswith("\\" + WROTE):
                groups[text].append(i)
        if not groups:
            continue
        text, same = max(groups.items(), key=lambda g: (len(g[1]), g[1]))
        if len(same) < 2:
            continue
        lines = text.decode("cp1252").split("\r\n")[1:]
        if lines and lines[-1] == "":
            lines = lines[:-1]
        K.write_text(script_path(mine), ["// Generated by dev\\migrate\\%s (what every %s without words of their "
                                         "own says)" % (MAKER, kind)] + lines)
        print("Wrote data\\Scripts\\%s.txt" % mine)
        for i in sorted(set(same)):
            K.remove_script("Talk to " + i, WROTE)
        shared += len(set(same))
        print("%-12s %d share it; %d keep their own" % (kind, len(set(same)), len(ids) - len(same)))
    print("%d copies gone" % shared if shared else "Nothing to share: done already.")


if __name__ == "__main__":
    main()
