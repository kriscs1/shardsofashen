def zone_cells(world, z):
    x1, y1, x2, y2 = z["box"]
    want = re.compile("^(%s)" % z["tile"])
    out = []
    for mx in range(x1, x2 + 1):
        for my in range(y1, y2 + 1):
            m = world.get_map(mx, my)
            if m is None:
                continue
            for y in range(YT):
                for x in range(XT):
                    c = m.rows[y][x]
                    if want.match(c) and "Roof(" not in c:
                        out.append((mx * XT + x, my * YT + y))
    return out


def free_cells(world, cells, taken):
    good = []
    for gx, gy in cells:
        c = world.cell(gx, gy)
        if c and "+" not in c and (gx, gy) not in taken and 1 <= gx % XT <= XT - 2 and 1 <= gy % YT <= YT - 2:
            good.append((gx, gy))
    return good


def spawn(world, gx, gy, mob, taken, opts=""):
    x, y = gx % XT + 1, gy % YT + 1
    if y == 1 or y == YT:                                     # (never on a map's top or bottom row: off the map)
        return
    zone = "Zone=%d,%d,%d,%d Chase=%d,%d,%d,%d" % (max(1, x - 3), max(1, y - 3), min(XT, x + 3), min(YT, y + 3),
                                                   max(1, x - 7), max(1, y - 7), min(XT, x + 7), min(YT, y + 7))
    world.line(gx, gy, "NPC", mob, ("Attitude=Bad %s %s" % (zone, opts)).strip())
    taken.add((gx, gy))


def stamp_ruin(world, gx, gy, w, h, rng, taken, wall="Ruined_Wall001"):
    """Four broken walls round a floor, a way in on the south."""
    door = gx + w // 2
    for y in range(gy, gy + h):
        for x in range(gx, gx + w):
            edge = y in (gy, gy + h - 1) or x in (gx, gx + w - 1)
            c = world.cell(x, y)
            if c is None or "Roof(" in c:
                continue
            base = c.split("+")[0]
            if edge and not (y == gy + h - 1 and abs(x - door) <= 1) and rng.random() < 0.75:
                world.put(x, y, wall)
            else:
                world.put(x, y, base)
            taken.add((x, y))


def make_zone(world, z, cells, rng, taken):
    """Its mobs, rocks, ruins and chest; returns where its giver stands."""
    free = free_cells(world, cells, taken)
    rng.shuffle(free)
    if not free:
        print("Nothing free in", z["key"])
        return None
    # (ruins, spread out)
    near = free[0]
    ruins = []
    for _ in range(max(2, len(free) // 700)):
        for tries in range(200):
            gx, gy = rng.choice(free)
            if all(abs(gx - a) + abs(gy - b) > 30 for a, b in ruins) and all(
                    (x, y) in set(free) or True for x in (gx, gx + 7) for y in (gy, gy + 6)):
                ruins.append((gx, gy))
                stamp_ruin(world, gx, gy, 8, 7, rng, taken)
                break
    chest = ruins[0] if ruins else near
    name = "Zone_Chest_%s" % z["key"]
    world.line(chest[0] + 4, chest[1] + 2, "StaticObject", "Chest", "Id=%s" % name)
    taken.add((chest[0] + 4, chest[1] + 2))
    lines = [HEADER, "01\tGet.Value\tATTRIBUTE\t%s\tVariable.1$" % name, "02\t>Conditional\t$Variable.1=0\t%02d" % (5 + len(z["loot"]) + 1),
             "03\tUpdate.Attribute\t%s\t=1" % name, "04\tPlay.Sound\tChest"]
    for k, (item, n) in enumerate(z["loot"]):
        lines.append("%02d\tGive.Item\t%s\t%d" % (5 + k, item, n))
    lines.append("%02d\tEnd" % (5 + len(z["loot"])))
    lines.append("%02d\tDisplay.Message\tCyan\tThe chest is empty.\tEmpty" % (5 + len(z["loot"]) + 1))
    lines.append("%02d\tEnd" % (5 + len(z["loot"]) + 2))
    with open(p("data", "Scripts", "Open %s.txt" % name), "w", encoding="cp1252", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    free = free_cells(world, cells, taken)
    rng.shuffle(free)
    i = 0
    for rock, n in z["rocks"]:
        # (in a cluster or two, as rock lies)
        for _ in range(max(1, n // 5)):
            cx, cy = free[i % len(free)]
            i += 1
            for k in range(5):
                gx, gy = cx + rng.randint(-2, 2), cy + rng.randint(-2, 2)
                c = world.cell(gx, gy)
                if c and "+" not in c and (gx, gy) not in taken:
                    world.put(gx, gy, c + "+Decor(%s)" % rock)
                    taken.add((gx, gy))
    count = max(6, len(free) // z["per"])
    for k in range(count):
        gx, gy = free[(i + k * 3) % len(free)]
        if (gx, gy) in taken or "+" in (world.cell(gx, gy) or "+"):
            continue
        spawn(world, gx, gy, z["mobs"][k % len(z["mobs"])], taken)
    return near


