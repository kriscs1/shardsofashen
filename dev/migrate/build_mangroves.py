def tree(seed):
    """A mangrove: a dark round crown over a tangle of arched stilt roots, standing in its own shade."""
    r = __import__("random").Random(seed)
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    trunk = (86, 62, 42, 255)
    # (the roots, arching down and out from the trunk)
    for dx in (-9, -6, -3, 2, 5, 8):
        x = 16 + dx
        d.line([(16, 18), (16 + dx * 0.6, 22), (x, 30)], fill=DARK, width=3)
    for dx in (-9, -6, -3, 2, 5, 8):
        x = 16 + dx
        d.line([(16, 18), (16 + dx * 0.6, 22), (x, 30)], fill=trunk, width=1)
    d.rectangle([14, 13, 18, 21], fill=DARK)
    d.rectangle([15, 13, 17, 21], fill=trunk)
    # (the crown: lobes, dark first so an outline's left round them)
    lobes = [(16 + r.randint(-9, 9), 9 + r.randint(-5, 4), r.randint(4, 7)) for _ in range(9)]
    for x, y, rad in lobes:
        d.ellipse([x - rad - 1, y - rad - 1, x + rad + 1, y + rad + 1], fill=DARK)
    for x, y, rad in lobes:
        d.ellipse([x - rad, y - rad, x + rad, y + rad], fill=(52, 86, 44, 255))
    for x, y, rad in lobes:
        d.ellipse([x - rad + 1, y - rad + 1, x + rad - 3, y + rad - 3], fill=(72, 112, 54, 255))
    for _ in range(26):
        x, y = r.randint(3, 28), r.randint(1, 17)
        if im.getpixel((x, y))[1] == 112:
            im.putpixel((x, y), (104, 142, 70, 255))
    return im


def bark():
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    for box, col in (((8, 12, 24, 20), (112, 68, 44, 255)), ((6, 17, 21, 24), (86, 52, 34, 255))):
        d.rectangle([box[0] - 1, box[1] - 1, box[2] + 1, box[3] + 1], fill=DARK)
    for box, col in (((8, 12, 24, 20), (112, 68, 44, 255)), ((6, 17, 21, 24), (86, 52, 34, 255))):
        d.rectangle(box, fill=col)
        for x in range(box[0] + 2, box[2], 4):
            d.line([(x, box[1] + 1), (x, box[3] - 1)], fill=(60, 34, 22, 255))
    return im


