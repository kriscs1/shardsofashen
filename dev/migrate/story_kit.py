def say(npc, text, *answers):
    """A conversation line: answers are (words, "@label") pairs."""
    r = ["Display.Conversation", npc, text]
    for words, goto in answers:
        r += [words, goto]
    return tuple(r)


def write_script(name, rows, maker):
    """data\\Scripts\\<name>.txt from rows: ("@label",) marks the next line; a field "@label" is that line's number.
    maker: the builder's file name, said on the first line. Written only when it changes."""
    numbered, labels, n = [], {}, 0
    for r in rows:
        if len(r) == 1 and r[0].startswith("@"):
            labels[r[0]] = n + 1
            continue
        n += 1
        numbered.append(r)
    assert n <= 99, "%s: %d lines (99 at most: carry on with Goto.Script)" % (name, n)
    out = ["// Generated by dev\\migrate\\%s" % maker]
    for i, r in enumerate(numbered, 1):
        fields = []
        for f in r:
            if isinstance(f, str) and f.startswith("@"):
                assert f in labels, "%s: no label %s" % (name, f)
                f = "%02d" % labels[f]
            fields.append(str(f) if str(f) != "" else " ")
        out.append("%02d\t%s" % (i, "\t".join(fields)))
    write_text(os.path.join(SCRIPTS, name + ".txt"), out)


def remove_script(name):
    path = os.path.join(SCRIPTS, name + ".txt")
    if os.path.exists(path):
        os.remove(path)
        print("Removed data\\Scripts\\%s.txt" % name)


def write_text(path, lines):
    """cp1252, CRLF, only when it changes."""
    data = "".join(ln + "\r\n" for ln in lines).encode("cp1252")
    if os.path.exists(path) and open(path, "rb").read() == data:
        return False
    with open(path, "wb") as f:
        f.write(data)
    return True


# ---------------------------------------------------------------- ini files (sections kept in their order)
def section(path, name, keys):
    """Writes each (key, value) of keys into [name] (ini.write: only the keys given change)."""
    for k, v in keys:
        if ini.read(name, k, "<unset>", path) != v:
            ini.write(name, k, v, path)


def _blocks(path):
    text = open(path, "rb").read().decode("cp1252").replace("\r\n", "\n")
    return re.split(r"(?m)^(?=\[)", text)


def _write_blocks(path, blocks):
    text = "".join(blocks).replace("\n", "\r\n")
    if open(path, "rb").read() != text.encode("cp1252"):
        open(path, "wb").write(text.encode("cp1252"))
        ini.forget(path)


def remove_section(path, name):
    blocks = _blocks(path)
    keep = [b for b in blocks if not b.startswith("[%s]\n" % name)]
    if len(keep) != len(blocks):
        _write_blocks(path, keep)
        print("Removed [%s] from %s" % (name, os.path.basename(path)))


def set_section(path, name, lines, after=None):
    """[name] made exactly lines ("Key=Value"), where it was (or after [after], or at the end)."""
    blocks = _blocks(path)
    body = "[%s]\n%s\n\n" % (name, "\n".join(lines))
    for i, b in enumerate(blocks):
        if b.startswith("[%s]\n" % name):
            blocks[i] = body
            break
    else:
        at = len(blocks)
        if after:
            for i, b in enumerate(blocks):
                if b.startswith("[%s]\n" % after):
                    at = i + 1
        if at == len(blocks) and blocks and not blocks[-1].endswith("\n\n"):
            blocks[-1] = blocks[-1].rstrip("\n") + "\n\n"
        blocks.insert(at, body)
    _write_blocks(path, blocks)


def quest(name, giver, attribute, stages, done, markers=None, kind="Main", chapter=None, requires=None,
          level=None, after=None, marker0=None):
    """Quests.ini [name]: stages {n: text} (n = the attribute's value), markers {n: place IDs ';'-joined}."""
    lines = ["Giver=%s" % giver, "Attribute=%s" % attribute]
    lines += ["Stage%d=%s" % (n, t) for n, t in sorted(stages.items())]
    lines += ["Done=%d" % done]
    markers = dict(markers or {})
    if marker0:
        markers[0] = marker0
    lines += ["Marker%d=%s" % (n, m) for n, m in sorted(markers.items())]
    lines += ["Type=%s" % kind]
    if chapter is not None:
        lines.append("Chapter=%d" % chapter)
    if level:
        lines.append("Requires.Level=%d" % level)
    if requires:
        lines.append("Requires.Quests=%s" % requires)
    set_section(QUESTS, name, lines, after)


def minimap_colour(tile, rgb):
    text = ini.read_text(COLOURS) if os.path.exists(COLOURS) else ""
    if ("\n%s\t" % tile) in ("\n" + text.replace("\r", "")):
        return
    with open(COLOURS, "a", encoding="cp1252", newline="\r\n") as f:
        f.write("%s\t%d %d %d\n" % ((tile,) + tuple(rgb)))


def copy_tile(new, old, **keys):
    """A tile section like old's, with keys changed (Use_Words= for Use.Words: dots can't be in a keyword)."""
    if not ini.section(new, TILES):
        for k, v in ini.section(old, TILES):
            ini.write(new, k, v, TILES)
    section(TILES, new, [(k.replace("_", "."), v) for k, v in keys.items()])


def copy_sprite(kind, src, dst):
    a, b = os.path.join(SPR, kind, src + ".png"), os.path.join(SPR, kind, dst + ".png")
    if not os.path.exists(b) or open(a, "rb").read() != open(b, "rb").read():
        shutil.copy(a, b)


