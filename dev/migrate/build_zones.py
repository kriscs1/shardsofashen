KEEP_AWAY = 34     # (tiles from a settlement's square)


def open_rect(world, gx, gy, w, h, taken, squares):
    if any(abs(gx - a) < KEEP_AWAY and abs(gy - b) < KEEP_AWAY for a, b in squares):
        return False
    for y in range(gy - 1, gy + h + 1):
        for x in range(gx - 1, gx + w + 1):
            c = world.cell(x, y)
            if c is None or (x, y) in taken or not c.split("+")[0].startswith("Grass"):
                return False
            for o in c.split("+")[1:]:
                if o.startswith(("Roof(", "Infront(", "Under(")) or (o.startswith("Decor(") and not W.WILD_DECOR.match(o[6:-1])):
                    return False
    return True


def clear_rect(world, gx, gy, w, h):
    for y in range(gy, gy + h):
        for x in range(gx, gx + w):
            world.put(x, y, world.cell(x, y).split("+")[0])


def find_spot(world, rng, w, h, taken, squares, tries=2500):
    for _ in range(tries):
        gx, gy = rng.randint(5 * XT, 28 * XT), rng.randint(-6 * YT, 21 * YT)
        world.get_map(gx // XT, gy // YT)
        world.get_map((gx + w) // XT, (gy + h) // YT)
        if open_rect(world, gx, gy, w, h, taken, squares):
            return gx, gy
    return None


