def grounds():
    world = {}
    for path in glob.glob(p("maps", "*,0.txt")):
        mx, my, _ = os.path.basename(path)[:-4].split(",")
        lines = open(path, "rb").read().decode("cp1252").split("\r\n")
        rows = [ln.split(":") for ln in lines[:YT]]
        world[(int(mx), int(my))] = (path, lines, rows)
    return world


def near(tiles, reach):
    """{(gx, gy)} within reach of any of tiles (by steps across, a diamond)."""
    out = set(tiles)
    edge = set(tiles)
    for _ in range(reach):
        grown = set()
        for x, y in edge:
            for c in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                if c not in out:
                    grown.add(c)
        out |= grown
        edge = grown
    return out


def main():
    art_and_data()
    world = grounds()
    if any("Mangrove00" in c for _, _, rows in world.values() for row in rows for c in row):
        print("Mangroves: already planted")         # (their mud counts as marsh: another pass would creep along the coast)
        return
    sea, marsh = set(), set()
    for (mx, my), (_, _, rows) in world.items():
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                t = c.split("+")[0]
                g = (mx * XT + x, my * YT + y)
                if t == "Water001":
                    sea.add(g)
                elif MARSHY.match(t):
                    marsh.add(g)
    shore = near(sea, SEA_REACH) & near(marsh, MARSH_REACH)
    done = planted = 0
    for (mx, my), (path, lines, rows) in world.items():
        ids = {(int(f[2]) - 1, int(f[3]) - 1) for f in (ln.split("\t") for ln in lines[YT:] if ln.startswith(("Id\t", "Trigger\t", "Lock\t")))
               if len(f) >= 4 and f[2].isdigit() and f[3].isdigit()}
        changed = False
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c != "Sand001" or (x, y) in ids or (mx * XT + x, my * YT + y) not in shore:
                    continue
                h = int(hashlib.md5(("%d,%d,%d,%d" % (mx, my, x, y)).encode()).hexdigest()[:8], 16)
                row[x] = "Marsh001"
                if h % 100 < TREES * 100:
                    row[x] += "+Decor(Mangrove00%d)" % (1 + h % 2 if h % 200 else 1)
                    planted += 1
                changed = True
        if changed:
            lines[:YT] = [":".join(r) for r in rows]
            open(path, "wb").write("\r\n".join(lines).encode("cp1252"))
            done += 1
    print("Mangroves: %d on %d maps" % (planted, done))


if __name__ == "__main__":
    main()
