"""Old Hob: a quest about an NPC who changes sides (Set.NPC.Attitude), round the locked house in Oakhollow.

Not run on its own: build_content.extend() calls extend() here after build_dragon (so the dragon quest doesn't wait for
it: it is a side quest) and before the quest notes and markers, so `python -I "dev\\migrate\\build_world.py"` builds it.

  * Old Hob's house in Oakhollow is boarded up (build_regions.locked_house); you climb in through the loose window.
    His diary (Hobs_Diary, Read) starts the quest: a giant spider bit him and he feels himself going wild.
  * Morwen the witch in Fenwick brews a Calming_Draught (a branch at the top of Talk to Witch).
  * Hob is a wild man in the western woods: an NPC whose map line says Attitude=Bad Id=OldHob, so he attacks on sight.
    Use the draught on him and Set.NPC.Attitude OldHob Good turns that one NPC Good (kept in the save).
  * If you left his savings in his chest, he gives you them. If you'd already taken them, he asks for them back: give
    them, or keep them and he goes wild again (Set.NPC.Attitude OldHob Bad): the quest ends either way.
  * HobQuest: 0 not started, 1 read the diary, 2 has the draught, 3 Hob is himself again, 4 done. HobAngry=1: he went
    wild again.
"""
W = C = R = None        # build_world, build_content, build_regions

QUEST = ("Old Hob", [
    ("Giver", "Hob"), ("Attribute", "HobQuest"),
    ("Stage0", "Old Hob of Oakhollow went missing, and his house is boarded up. One of its shutters hangs loose..."),
    ("Stage1", "Old Hob's diary: a giant spider bit him and he feels himself going wild. Ask Morwen the witch in Fenwick for a cure."),
    ("Stage2", "Find the wild man in the western woods of the Wildwood and use Morwen's calming draught on him."),
    ("Stage3", "Hob is himself again! Talk to him."),
    ("Done", "4")])
WOODS = (0, 6)              # the map Hob roams (the western woods, round the second watch stone)
HOB_ID = "OldHob"           # his map line's Id=: the one NPC Set.NPC.Attitude changes


def entities():
    C.ENTITIES.update({
        "Hob": [("Type", "NPC"), ("Attitude", "Bad"), ("Use.Words", "Talk to"),
                ("Examine.Info", "A wild-eyed man in rags, snarling and twitching. There's something familiar about him."),
                ("Hitpoints", "28"), ("Attack.Speed", "1.2"), ("Strength", "3"), ("Defence", "4"), ("Aggro.Range", "90"),
                ("Weapon.Range", "0"), ("Movement.Speed", "2"), ("Aggressive", "1"), ("Respawn", "40")],
        "Calming_Draught": C.item(0, "Morwen's calming draught: it smells of bog myrtle and honey. For Old Hob.", droppable=0),
        "Hobs_Diary": C.station("Read", "Old Hob's diary, swollen with damp."),
    })
    C.MOVEMENT["Hob"] = (2, 3, "0.4", "2-6")


def place():
    """Hob in the western woods (a free open spot away from the watch stone), his diary in his house."""
    import build_scenery
    open_ground = {"Grass001", "Weed001", "Tall_Grass001"} | set(build_scenery.WALK_DECOR)
    mx, my = WOODS
    name = "%d,%d,0" % (mx, my)
    rows = W.MAPS[name]["rows"]
    stone = R.SITES["WatchStone2"]
    for x, y in R.spots(R.GRID, R.BUSY, mx, my, 12, "hob", [stone]):
        near = [W.LEGEND.get(rows[yy - 1][xx - 1], "") for yy in range(y - 1, y + 2) for xx in range(x - 1, x + 2)
                if 1 <= xx <= W.MAP_W and 1 <= yy <= W.MAP_H]
        if all(t in open_ground for t in near):
            px, py = W.at(x, y)
            W.MAPS[name]["entities"].append(("BadNPC", "Hob", px, py, "Id=%s Zone=%d,%d,%d,%d" % (HOB_ID, x - 2, y - 2, x + 2, y + 2)))
            break
    else:
        raise AssertionError("no room for Old Hob in " + name)
    if R.LOCKED.get("diary"):
        ix, iy = R.LOCKED["diary"]
        W.MAPS[R.LOCKED["map"]]["entities"].append(W.obj("Hobs_Diary", ix, iy))


def conv(text, *answers):
    return R.conv("Hob", text, *answers)


