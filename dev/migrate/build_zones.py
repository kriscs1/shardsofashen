def lay_dust(world):
    done = []
    rng = random.Random(62)
    for gx, gy in ring_of(14.5 * XT, 10.2 * YT, 2.6 * XT, 4.0 * YT, 11):
        c = world.cell(gx, gy)
        if c is None:
            continue
        t = c.split("+")[0]
        if t.startswith(("Grass", "Heath", "Moss", "Marsh", "Sand")) and "Roof(" not in c:
            over = c.split("+")[1:]
            keep = [o for o in over if not (o.startswith("Decor(") and W.WILD_DECOR.match(o[6:-1]))]
            keep += ["Decor(%s)" % rng.choice(("Dead_Tree001", "Dead_Tree002", "Rock001", "Rock002", "Pebbles001"))] \
                if not keep and rng.random() < 0.035 else []
            world.put(gx, gy, "+".join(["Dust001"] + keep))
            done.append((gx, gy))
    return done


def lay_rime(world):
    """A snowy, icy island south of the snow, in the sea: new maps, an ice bridge to it."""
    cx, cy = 18.8 * XT, 26.4 * YT
    land = []
    rng = random.Random(63)
    for mx in range(13, 26):
        for my in range(23, 31):
            world.get_map(mx, my, make="Water001")
    for gx, gy in ring_of(cx, cy, 4.6 * XT, 2.8 * YT, 21):
        if world.cell(gx, gy) is None:
            continue
        roll = rng.random()
        tile = "Snow001"
        decor = ""
        if (int(gx / 9) * 7 + int(gy / 7) * 13) % 5 == 0:
            tile = "Ice001"
        elif roll < 0.05:
            decor = "+Decor(Snow_Pine001)"
        elif roll < 0.08:
            decor = "+Decor(Snow_Rock001)"
        world.put(gx, gy, tile + decor)
        land.append((gx, gy))
    # (the bridge: a wandering span of ice from the north shore)
    x = 18 * XT + 12
    y = 22 * YT + 6
    while world.cell(x, y) is not None and (world.cell(x, y).startswith("Water") or y < 23 * YT + 3):
        for k in (-2, -1, 0, 1, 2):
            c = world.cell(x + k, y)
            if c and c.split("+")[0].startswith("Water"):
                world.put(x + k, y, "Ice001")
        x += rng.choice((-1, 0, 0, 1))
        y += 1
        if y > 28 * YT:
            break
    return land


