# ---------------------------------------------------------------- pictures (pygame)
_pg = None


def pg():
    global _pg
    if _pg is None:
        import pygame
        pygame.init()
        pygame.display.set_mode((1, 1))
        _pg = pygame
    return _pg


def surface(w=32, h=32):
    p = pg()
    return p.Surface((w, h), p.SRCALPHA)


def outlined(s, col=(28, 20, 16)):
    """A 1 px dark outline round what's drawn (the mask-silhouette method): every see-through pixel beside a drawn one."""
    p = pg()
    w, h = s.get_size()
    out = s.copy()
    for y in range(h):
        for x in range(w):
            if s.get_at((x, y))[3] > 0:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h and s.get_at((nx, ny))[3] > 0:
                    out.set_at((x, y), col + (255,))
                    break
    return out


def save(kind, name, s):
    """sprites\\<kind>\\<name>.png, written only when it changes."""
    p = pg()
    path = os.path.join(SPR, kind, name + ".png")
    tmp = path + ".new.png"
    p.image.save(s, tmp)
    if os.path.exists(path) and open(path, "rb").read() == open(tmp, "rb").read():
        os.remove(tmp)
        return False
    os.replace(tmp, path)
    return True


def load(kind, name):
    return pg().image.load(os.path.join(SPR, kind, name + ".png")).convert_alpha()


# ---------------------------------------------------------------- sounds (22050 Hz mono)
RATE = 22050


def wav(name, samples, gain=0.9):
    """sounds\\<name>.wav from samples (-1..1), written only when it changes."""
    peak = max(1e-6, max(abs(s) for s in samples))
    k = gain / peak if peak > gain else 1.0
    data = b"".join(struct.pack("<h", int(max(-1, min(1, s * k)) * 30000)) for s in samples)
    path = os.path.join(ROOT, "sounds", name + ".wav")
    tmp = path + ".new"
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(data)
    if os.path.exists(path) and open(path, "rb").read() == open(tmp, "rb").read():
        os.remove(tmp)
        return False
    os.replace(tmp, path)
    return True


def tone(freq, secs, harmonics=(1.0,), attack=0.01, release=0.05, glide=0.0, vibrato=0.0):
    out, phase = [], 0.0
    n = int(RATE * secs)
    for i in range(n):
        t = i / RATE
        f = freq * (1 + glide * t / secs) * (1 + vibrato * math.sin(2 * math.pi * 5.5 * t))
        phase += 2 * math.pi * f / RATE
        v = sum(a * math.sin(phase * (k + 1)) for k, a in enumerate(harmonics))
        env = min(1.0, t / attack) * min(1.0, (secs - t) / release)
        out.append(v * env)
    return out


def silence(secs):
    return [0.0] * int(RATE * secs)
