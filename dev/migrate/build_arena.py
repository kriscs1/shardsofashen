"""The arena: where players fight each other (the multiplayer server's PvP). Run it again after rebuilding the world
(build_world.py rewrites the maps): it makes what's missing and leaves the rest as it is.

  python -I "dev\\migrate\\build_arena.py"

  * maps\\0,0,10.txt  the arena, on a level of its own (nothing joins it at its edges): stone walls, a paved walk round
    the edge for the crowd, and a sand pit in the middle. Players can only fight on the sand (Config [PvP]), so
    whoever stands on the paving is safe.
  * The Arena Master (a guard, Id=Arena_Master) in Ashford takes you there; the Arena Keeper (Id=Arena_Keeper) by the
    arena's gate brings you back. data\\Scripts\\Talk to Arena_Master.txt, Talk to Arena_Keeper.txt, and 0,0,10.txt (the
    arena's rules, said as you arrive).
  * Config [PvP]: Maps, Ground, and where you wake when you're beaten (nothing is lost: no gold, no grave).
  * data\\Music.ini [Maps] 0,0,10=Danger.
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from ashen import ini  # noqa: E402

ARENA = "0,0,10"
TOWN = "11,4,0"                        # (Ashford, on the mainland)
XT, YT = 25, 21
SPAWN = (12, 18)                       # tile (1-based) the beaten wake on, and arrivals land on: by the gate
KEEPER = (10, 19)


def arena_cells():
    cells = {}
    for y in range(1, YT + 1):
        for x in range(1, XT + 1):
            if x in (1, XT) or y in (1, YT):
                cells[(x, y)] = "Stone_Wall001"
            elif ((x - 13) / 8.6) ** 2 + ((y - 10.5) / 6.4) ** 2 <= 1:
                cells[(x, y)] = "Sand001"
            else:
                cells[(x, y)] = "Paving001"
    decor = {}
    for x in (4, 8, 18, 22):                    # torches and banners along the walls
        decor[(x, 1)] = "Wall_Torch001"
        decor[(x, YT)] = "Wall_Torch001"
    for y in (5, 10, 15):
        decor[(1, y)] = "Wall_Torch001"
        decor[(XT, y)] = "Wall_Torch001"
    for x in (6, 11, 15, 20):
        decor[(x, 1)] = "Banner001"
    for x, y in ((3, 3), (23, 3), (3, 19), (23, 19)):       # pillars in the corners of the walk
        decor[(x, y)] = "Pillar001"
    decor[(12, 2)] = "Statue001"                            # the champions' statues, over the pit
    decor[(14, 2)] = "Statue002"
    for x in (5, 7, 9, 17, 19, 21):                         # benches for the crowd
        decor[(x, 2)] = "Bench001"
    for x, y in ((2, 8), (2, 13), (24, 8), (24, 13)):
        decor[(x, y)] = "Bench001"
    for x, y in ((8, 19), (16, 19)):
        decor[(x, y)] = "Lamp_Post001"
    return cells, decor


def write_arena():
    path = os.path.join(ROOT, "maps", ARENA + ".txt")
    if os.path.exists(path):
        print("maps\\%s.txt is there already" % ARENA)
        return
    cells, decor = arena_cells()
    rows = []
    for y in range(1, YT + 1):
        row = []
        for x in range(1, XT + 1):
            c = cells[(x, y)]
            if (x, y) in decor:
                c += "+Decor(%s)" % decor[(x, y)]
            row.append(c)
        rows.append(":".join(row))
    lines = rows + [
        "NPC\tGuard\t%d\t%d\tAttitude=Good Stand=1 Id=Arena_Keeper" % ((KEEPER[0] - 1) * 32, (KEEPER[1] - 1) * 32 - 8),
        "Id\tArena_Gate\t%d\t%d" % SPAWN,
    ]
    with open(path, "w", encoding="cp1252", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Made maps\\%s.txt" % ARENA)


def write_script(name, lines):
    path = os.path.join(ROOT, "data", "Scripts", name + ".txt")
    if os.path.exists(path):
        print("data\\Scripts\\%s.txt is there already" % name)
        return
    with open(path, "w", encoding="cp1252", newline="\r\n") as f:
        f.write("// Generated by dev\\migrate\\build_arena.py\n" + "\n".join(lines) + "\n")
    print("Made data\\Scripts\\%s.txt" % name)


def spawn_pixels():
    return (SPAWN[0] - 1) * 32, (SPAWN[1] - 1) * 32 - 8


def map_lines(name):
    return ini.read_text(os.path.join(ROOT, "maps", name + ".txt")).replace("\r", "").split("\n")


def master_position():
    for ln in map_lines(TOWN):
        parts = ln.split("\t")
        if len(parts) >= 5 and "Id=Arena_Master" in parts[4]:
            return int(float(parts[2])), int(float(parts[3]))
    return None


def place_master():
    """The Arena Master in Ashford, on the clear spot nearest the middle of the village."""
    if master_position() is not None:
        print("The Arena Master is in Ashford already")
        return master_position()
    lines = map_lines(TOWN)
    tiles = os.path.join(ROOT, "data", "Tiles.ini")
    taken = []
    for ln in lines[YT:]:
        parts = ln.split("\t")
        if len(parts) >= 4 and parts[0] not in ("Lock", "Trigger", "Id"):
            try:
                taken.append((float(parts[2]), float(parts[3])))
            except ValueError:
                pass
    best = None
    for ty in range(2, YT):
        for tx in range(2, XT):
            ok = True
            for dy in (-1, 0, 1, 2):            # (the tile below too: where the keeper sends you back to)
                if ty + dy > YT:
                    ok = False
                    continue
                row = lines[ty - 1 + dy].split(":")
                for dx in (-1, 0, 1):
                    c = row[tx - 1 + dx]
                    if "+" in c or "0" in ini.read(c, "Walkable.Data", "1" * 49, tiles):
                        ok = False
            px, py = (tx - 1) * 32, (ty - 1) * 32
            if ok and all(math.hypot(px - x, py - y) > 64 for x, y in taken):
                d = math.hypot(tx - 13, ty - 11)
                if best is None or d < best[0]:
                    best = (d, px, py)
    if best is None:
        print("ERROR - no clear spot in Ashford for the Arena Master")
        return None
    _, px, py = best
    while lines and lines[-1] == "":
        lines.pop()
    lines.append("NPC\tGuard\t%d\t%d\tAttitude=Good Stand=1 Id=Arena_Master" % (px, py - 8))
    with open(os.path.join(ROOT, "maps", TOWN + ".txt"), "w", encoding="cp1252", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("The Arena Master stands in Ashford at %d,%d" % (px, py))
    return master_position()


STONE = (15, 18)                       # the arena's shardstone, on the walk by the gate (its place Id the tile below)


def arena_stone():
    """A shardstone by the arena's gate, [Arena] in Shardstones.ini: active to you once you've spoken to the Arena
    Master (no Shards), so you can come from any stone you've woken. Talk to Arena_Master says so (written again)."""
    path = os.path.join(ROOT, "maps", ARENA + ".txt")
    text = ini.read_text(path)
    if "Waystone_Arena" not in text:
        lines = text.replace("\r", "").rstrip("\n").split("\n")
        lines += ["StaticObject\tShardstone\t%d\t%d" % ((STONE[0] - 1) * 32, (STONE[1] - 1) * 32),
                  "Id\tWaystone_Arena\t%d\t%d" % (STONE[0], STONE[1] + 1)]
        with open(path, "w", encoding="cp1252", newline="\r\n") as f:
            f.write("\n".join(lines) + "\n")
        print("The arena's shardstone set down")
    stones = os.path.join(ROOT, "data", "Shardstones.ini")
    if "[Arena]" not in ini.read_text(stones):
        with open(stones, "a", encoding="cp1252", newline="\r\n") as f:
            f.write("\n[Arena]\nTitle=The Arena\n")
    sx, sy = spawn_pixels()
    rows = [
        "01\tGet.Value\tATTRIBUTE\tWaystone.Arena\tVariable.1",
        "02\t>Conditional\t$Variable.1<1\t05",
        "03\tUpdate.Attribute\tWaystone.Arena\t=1",
        "04\tDisplay.Message\tCyan\tThe Arena Master taps a little rune-token against your hand. \"There: the arena's "
        "shardstone knows you now. Any stone you've woken will take you to it.\"\t-",
        "05\tDisplay.Conversation\tGuard\tStep up, step up! In the arena you may fight other adventurers, for glory and "
        "nothing else: no gold lost, no grave. Only on the sand, mind: the paving round it is for the crowd.\t"
        "Take me to the arena.\t06\tNot today.\t08",
        "06\tPlay.Sound\tDoor",
        "07\tTeleport\t%d,%d\t%s" % (sx, sy, ARENA),
        "08\tEnd",
    ]
    with open(os.path.join(ROOT, "data", "Scripts", "Talk to Arena_Master.txt"), "w", encoding="cp1252",
              newline="\r\n") as f:
        f.write("// Generated by dev\\migrate\\build_arena.py\n" + "\n".join(rows) + "\n")


def main():
    write_arena()
    arena_stone()
    master = place_master()
    if master is None:
        return
    sx, sy = spawn_pixels()
    # (in the arena the whole pit can be seen, for the crowd: no fog of war; back in town it's as it was)
    view = int(float(ini.read("Gameplay", "FogOfWar.Viewable.Distance", "200", os.path.join(ROOT, "data", "Config.ini"))))
    write_script("Talk to Arena_Master", [
        "01\tDisplay.Conversation\tGuard\tStep up, step up! In the arena you may fight other adventurers, for glory and "
        "nothing else: no gold lost, no grave. Only on the sand, mind: the paving round it is for the crowd.\t"
        "Take me to the arena.\t02\tNot today.\t04",
        "02\tPlay.Sound\tDoor",
        "03\tTeleport\t%d,%d\t%s" % (sx, sy, ARENA),
        "04\tEnd",
    ])
    write_script("Talk to Arena_Keeper", [
        "01\tDisplay.Conversation\tGuard\tHad enough? I can take you back to Ashford.\tBack to Ashford, please.\t02\t"
        "I'll stay a while.\t05",
        "02\tPlay.Sound\tDoor",
        "03\tEdit.View.Distance\t%d" % view,
        "04\tTeleport\t%d,%d\t%s" % (master[0], master[1] + 40, TOWN),
        "05\tEnd",
    ])
    write_script(ARENA, [
        "01\tDisplay.Message\tDarkRed\tThe arena! Step onto the sand to fight other players (right-click them: Attack). "
        "The paving is safe. Beaten, you lose nothing: you wake by the gate.",
        "02\tEdit.View.Distance\t0",
        "03\tEnd",
    ])
    cfg = os.path.join(ROOT, "data", "Config.ini")
    if not ini.read("PvP", "Maps", "", cfg):
        ini.write("PvP", "Maps", ARENA, cfg)
        ini.write("PvP", "Ground", "Sand001", cfg)
        ini.write("PvP", "Respawn.Map", ARENA, cfg)
        ini.write("PvP", "Respawn.X", str(sx), cfg)
        ini.write("PvP", "Respawn.Y", str(sy), cfg)
        print("Config [PvP] written")
    music = os.path.join(ROOT, "data", "Music.ini")
    if not ini.read("Maps", ARENA, "", music):
        ini.write("Maps", ARENA, "Danger", music)


if __name__ == "__main__":
    main()
