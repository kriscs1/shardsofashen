def filled(lines):
    """Script lines with every number there (a jump's gap filled with an End nothing reaches: validate.py wants them in a row)."""
    out, want = [], 1
    for ln in lines:
        n = int(ln.split("\t")[0])
        while want < n:
            out.append("%02d\tEnd" % want)
            want += 1
        out.append(ln)
        want = n + 1
    return out


