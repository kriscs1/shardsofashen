"""Feed the cats and the dogs: Feed on each (Use.Words), and a script that takes the first thing it would eat from
what you carry (a cat: fish, then poultry; a dog: meat, then poultry, then fish). The named cats eat by name.
Safe to run again (the scripts are written again, the same).

  python -I "dev\\migrate\\feed_animals.py"
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from ashen import ini  # noqa: E402
from build_isle import DATA  # noqa: E402
from build_cats import CATS, NAMED  # noqa: E402

CAT_FOOD = ["Raw_Herring", "Raw_Trout", "Raw_Salmon", "Cooked_Herring", "Cooked_Trout", "Cooked_Salmon", "Raw_Poultry",
            "Cooked_Poultry"]
DOG_FOOD = ["Raw_Meat", "Cooked_Meat", "Raw_Poultry", "Cooked_Poultry", "Raw_Herring", "Cooked_Herring"]
# who: (what it eats, how it eats it - {food} is the food, "a cat" / "a dog" for the refusal)
EATERS = {"Dog": (DOG_FOOD, "The dog gulps down the {food} and wags its whole back end.", "a dog")}
for _cat in CATS:
    EATERS[_cat] = (CAT_FOOD, "The cat eats the {food} in neat little bites, then washes its whiskers.", "a cat")
for _who, (_kind, _, _, _) in NAMED.items():
    EATERS[_who] = (CAT_FOOD, _who + " eats the {food} in three bites, then looks up at you for more.", "a cat")
EATERS["Throne_Jimmy"] = EATERS["Jimmy"]            # (Jimmy in the throne room, once you're king)


def write(name, lines):
    path = os.path.join(DATA, "Scripts", name + ".txt")
    with open(path, "w", encoding="cp1252", newline="\r\n") as f:
        f.write("// Generated by dev\\migrate\\feed_animals.py\n" + "\n".join(lines) + "\n")


def feed_script(foods, eats, what):
    """01 too far?  then for each food: have one? take it, say so, the end.  Else: nothing it would eat."""
    n = 2 + 4 * len(foods)                       # (the line after the foods: nothing to give)
    lines = ["01\t>Distance.From.Clicked.Entity\t40\t%02d" % (n + 2)]
    for i, food in enumerate(foods):
        k = 2 + 4 * i
        lines += ["%02d\t>Got.Item\t%s\t1\t%02d" % (k, food, k + 4),
                  "%02d\tTake.Item\t%s\t1" % (k + 1, food),
                  "%02d\tDisplay.Message\tCyan\t%s\tEatFood" % (k + 2, eats.format(food=food.replace("_", " ").lower())),
                  "%02d\tEnd" % (k + 3)]
    lines += ["%02d\tDisplay.Message\tDarkRed\tYou have nothing %s would eat.\tDenied" % (n, what),
              "%02d\tEnd" % (n + 1),
              "%02d\tDisplay.Message\tDarkRed\tYou are too far away!\tDenied" % (n + 2),
              "%02d\tEnd" % (n + 3)]
    return lines


def main():
    ents = os.path.join(DATA, "Entities.ini")
    for kind in ["Dog"] + list(CATS):
        words = [w.strip() for w in (ini.read(kind, "Use.Words", "", ents) or "").split(",") if w.strip()]
        if "Feed" not in words:
            words.insert(1, "Feed")                  # (after Stroke / Pet)
            ini.write(kind, "Use.Words", ",".join(words), ents)
    for who, (foods, eats, what) in EATERS.items():
        write("Feed " + who, feed_script(foods, eats, what))
    print("Feed: the dog and the cats (%s by name)" % ", ".join(NAMED))


if __name__ == "__main__":
    main()
