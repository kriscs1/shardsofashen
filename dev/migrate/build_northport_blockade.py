"""Northport shut (the owner's wish, to make the start feel directed): the Parliament has the roads out of the city closed
(raiders on every one of them) until the Speaker says who may pass, so a new arrival from the Isle is sent to the City Hall
and doesn't wander off into country that's too hard for them.

  * A ring of Lock lines just inside the city's edge (every land cell of it that isn't mountain), open once
    ParliamentQuest>=2 (the Speaker has given you the Parliament's letter). A Lock is each player's own and keeps NPCs in too.
    It only stops you leaving: the shardstone, the ferry and everything inside stay as they were.
  * A city guard at each road out (Port_Guard, in Northport's blue), who says why, and what's changed once you've the
    Speaker's word. Scripts `Talk to Northport_<Way>_Gate_Guard`.

  python -I "dev\migrate\build_northport_blockade.py"

Run once (a second run finds the locks there and stops).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import world_edit as W                                              # noqa: E402

X1, X2, Y1, Y2 = 52, 147, 86, 144                                    # (the ring: Northport's own ground)
OPEN = "$Attr.ParliamentQuest>=2"
SAYS = "The city guard have the roads shut, by order of the Parliament."
GATES = [("East", (147, 122), (-1, 1), "E"), ("East_2", (147, 133), (-1, 1), "E"),
         ("South", (103, 144), (1, -1), "S"), ("West", (52, 137), (1, 1), "W")]
NAMES = {"East": "Gate_Sergeant_Ames", "East_2": "Gate_Sergeant_Pike", "South": "Gate_Sergeant_Vell", "West": "Gate_Sergeant_Orr"}


def script(gate):
    return "\r\n".join([
        "// Generated by dev\\migrate\\build_northport_blockade.py",
        "01\tGet.Value\tATTRIBUTE\tParliamentQuest\tVariable.1$",
        "02\t>Conditional\t$Variable.1>=2\t06",
        "03\tDisplay.Conversation\tPort_Guard\tHalt. The Parliament's had the roads out of Northport shut: goblins and worse on every one, and the "
        "patrols that went out haven't all come back.\\Nobody leaves on their own account. The Speaker says who may pass, "
        "in the City Hall.\tUnderstood.\t04",
        "04\tEnd",
        "05\tEnd",
        "06\tDisplay.Conversation\tPort_Guard\tThe Speaker's word on you? Then the road's yours. Keep your sword near and "
        "your back to the wall at night.\tThank you.\t07",
        "07\tEnd", ""])


def main():
    w = W.World(0)
    if any(ln.startswith("Lock\t") and OPEN in ln and "Parliament" in ln for m in w.maps.values() for ln in m.ents):
        print("Northport's roads are shut already")
        return
    ring = []
    for x in range(X1, X2 + 1):
        ring += [(x, Y1), (x, Y2)]
    for y in range(Y1 + 1, Y2):
        ring += [(X1, y), (X2, y)]
    n = 0
    for gx, gy in ring:
        c = w.cell(gx, gy)
        if c is None or W.watery(c) or W.PEAKY.match(W.parts(c)[0]) or W.parts(c)[0].startswith("Sea_Rock"):
            continue
        m, x, y = w.at(gx, gy)
        m.ents.append("Lock\t%d\t%d\t%s\t%s" % (x, y, OPEN, SAYS))
        w.changed.add(m.name)
        n += 1
    for way, (gx, gy), (dx, dy), face in GATES:
        pid = "Northport_%s_Gate_Guard" % way
        w.place(gx + dx, gy + dy, "NPC", "Port_Guard", "Attitude=Good Stand=1 Face=%s Id=%s Name=%s" % (face, pid, NAMES[way]), dy=0)
        path = os.path.join(W.SCRIPTS, "Talk to %s.txt" % pid)
        open(path, "wb").write(script(way).encode("cp1252"))
    w.save()
    print("Northport shut: %d lock cells, %d guards" % (n, len(GATES)))


if __name__ == "__main__":
    main()
