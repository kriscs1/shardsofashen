def join_pieces(family):
    tiles = Ini(TILES)
    out = {}
    for s in tiles.sections:
        if re.fullmatch(family + r"\d{3}", s[0]):
            j = tiles.get(s[0], "Joins")
            if j:
                out[frozenset(j) if j != "-" else frozenset()] = s[0]
    return out


def fence_round(atlas, box, gaps, family):
    """A Join set's fence round a rectangle, gaps left for gates: each cell the piece that meets its neighbours."""
    pieces = join_pieces(family)
    x1, y1, x2, y2 = box
    line = {(x, y) for x in range(x1, x2 + 1) for y in (y1, y2)} | {(x, y) for y in range(y1, y2 + 1) for x in (x1, x2)}
    line -= set(gaps)
    for c in line:
        j = frozenset(k for k, (dx, dy) in zip("NESW", ((0, -1), (1, 0), (0, 1), (-1, 0)))
                      if (c[0] + dx, c[1] + dy) in line)
        put(atlas, c, decor=pieces.get(j) or pieces[frozenset()])


def lay_graveyard(atlas):
    x1, y1, x2, y2 = GRAVEYARD
    for c in box_cells(GRAVEYARD):
        put(atlas, c, "Lawn001", decor="", under="")
    gate = [(x, y2) for x in GRAVE_GATE]
    for x in GRAVE_GATE:                                       # (gravel up the middle, and across below the firstborn)
        for y in range(y1 + 3, y2 + 2):
            put(atlas, (x, y), "Gravel001")
    for x in range(x1 + 1, x2):
        put(atlas, (x, y1 + 4), "Gravel001")
    for y in (y2 + 1,):
        for x in GRAVE_GATE:
            put(atlas, (x, y), "Gravel001")
    fence_round(atlas, GRAVEYARD, gate, "Iron_Fence")
    atlas.place_id(GRAVE_GATE[0], y2 + 1, "Galaith_Graveyard")
    for k, (pid, _) in enumerate(ROYAL_STONES):                # (the firstborn, along the north side, in a row)
        c = (x1 + 5 + k * 4 + (2 if k >= 3 else 0), y1 + 2)
        put(atlas, c, decor="Royal_Cenotaph001")
        atlas.place_id(c[0], c[1], pid)
    stones = ["Headstone001", "Headstone002", "Stone_Cross001", "Headstone003", "Grave_Slab001"]
    columns = [x1 + 2 + 3 * k for k in range(4)] + [x2 - 2 - 3 * k for k in range(3, -1, -1)]
    k = 0
    for y in (y1 + 6, y1 + 9):
        for x in columns:
            pid, _ = GRAVES[k]
            put(atlas, (x, y), decor=stones[int(h01("stone", pid) * len(stones))])
            atlas.place_id(x, y, pid)
            k += 1
    for c in ((x1 + 1, y1 + 1), (x2 - 1, y1 + 1), (x1 + 1, y2 - 1), (x2 - 1, y2 - 1)):   # (a yew in each corner)
        put(atlas, c, decor="Yew_Tree001")
    for x in (GRAVE_GATE[0] - 3, GRAVE_GATE[1] + 3):           # (a seat, each side of the gate; lamps by it)
        put(atlas, (x, y2 - 1), decor="Bench001")
    put(atlas, (GRAVE_GATE[0] - 1, y2 - 1), decor="Flower_Urn001")
    put(atlas, (GRAVE_GATE[1] + 1, y2 - 1), decor="Flower_Urn001")
    atlas.line(x1 + 8, y2 - 2, "NPC", "Villager", "Attitude=Good Id=Galaith_Sexton Name=Sexton Look=0 Zone=%s" %
               atlas.zone(x1 + 2, y1 + 5, x2 - 2, y2 - 2, x1 + 8, y2 - 2), dy=-8)


def lay_orchard(atlas):
    x1, y1, x2, y2 = ORCHARD
    for c in box_cells(ORCHARD):
        put(atlas, c, "Lawn001", decor="", under="")
    gaps = [(x, y) for x in ORCHARD_GATE for y in (y1, y2)]
    for x in ORCHARD_GATE:
        for y in range(y1, y2 + 1):
            put(atlas, (x, y), "Gravel001")
    mid = (y1 + y2) // 2
    for x in range(x1 + 1, x2):
        put(atlas, (x, mid), "Gravel001")
    fence_round(atlas, ORCHARD, gaps, "Wood_Fence")
    atlas.place_id(ORCHARD_GATE[0], y1 + 1, "Galaith_Orchard")
    columns = [x1 + 2 + 3 * k for k in range(4)] + [x2 - 2 - 3 * k for k in range(3, -1, -1)]
    rows = [y1 + 2, y1 + 5, y1 + 8, mid + 2, mid + 5, mid + 8]
    n_trees = 0
    for y in rows:
        for x in columns:
            pear = (x > ORCHARD_GATE[0]) == (y < mid)            # (two corners of apples, two of pears)
            put(atlas, (x, y), decor="Pear_Tree001" if pear else "Apple_Tree001")
            n_trees += 1
            if not pear and y + 1 not in (mid, y2) and h01("windfall", x, y) < 0.35:
                put(atlas, (x, y + 1), decor="Fallen_Apples001")
    for c in ((x1 + 1, mid + 1), (ORCHARD_GATE[0] - 1, y1 + 1), (ORCHARD_GATE[1] + 1, y2 - 1)):
        put(atlas, c, decor="Fruit_Crate001")
    for y in (y1 + 3, y1 + 4, y2 - 4, y2 - 3):
        put(atlas, (x2 - 1, y), decor="Beehive001")
    put(atlas, (ORCHARD_GATE[1] + 1, mid - 1), decor="Bench001")
    atlas.line(ORCHARD_GATE[0] - 3, mid + 1, "NPC", "Farmer", "Attitude=Good Id=Galaith_Gardener Name=Gardener Look=0 "
               "Zone=%s" % atlas.zone(x1 + 2, y1 + 2, x2 - 2, y2 - 2, ORCHARD_GATE[0] - 3, mid + 1), dy=-8)
    return n_trees


