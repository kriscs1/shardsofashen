def outlined(im, colour=(24, 16, 34, 255)):
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    px, src = out.load(), im.load()
    w, h = im.size
    for y in range(h):
        for x in range(w):
            if src[x, y][3] > 0:
                continue
            if any(0 <= x + dx < w and 0 <= y + dy < h and src[x + dx, y + dy][3] > 120
                   for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                px[x, y] = colour
    out.alpha_composite(im)
    return out


def abomination(frame):
    """A hunched mass of dark violet flesh, jagged Shard crystals grown through it, three burning cores, too many limbs:
    it drags itself along on the near ones (facing east). frame: a, b or c of its lurch; the poses keep one ground line."""
    rng = random.Random("abomination")
    im = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    flesh, dark, pale = (70, 44, 92), (44, 26, 62), (100, 68, 128)
    crystal, lit, deep = (150, 110, 226), (214, 190, 255), (88, 58, 170)
    bob = (0, -1, -1)[frame]
    swing = (0, 3, -3)[frame]

    def limb(x, y, dx, far):
        c = dark if far else flesh
        d.line((x, y + bob, x + dx // 2, y + 8 + bob), fill=c, width=4)
        d.line((x + dx // 2, y + 8 + bob, x + dx, 44), fill=c, width=3)
        d.polygon([(x + dx - 3, 45), (x + dx + 3, 45), (x + dx, 41)], fill=deep)       # (a crystal claw)

    for x, y, dx in ((12, 28, -3 - swing), (34, 28, 3 + swing)):                       # (the far limbs first)
        limb(x, y, dx, True)
    d.ellipse((8, 15 + bob, 40, 39 + bob), fill=flesh)                                 # (the mass of it)
    d.ellipse((24, 11 + bob, 45, 31 + bob), fill=flesh)                                # (what serves it for shoulders)
    d.ellipse((10, 26 + bob, 38, 40 + bob), fill=dark)
    for _ in range(40):
        x, y = rng.randrange(10, 42), rng.randrange(14, 38)
        d.point((x, y + bob), fill=rng.choice([pale, dark, dark]))

    def crystal_at(x, y, h, lean):
        y += bob
        pts = [(x - 3, y), (x + lean, y - h), (x + 3, y)]
        d.polygon(pts, fill=crystal)
        d.polygon([(x - 3, y), (x + lean, y - h), (x - 1, y)], fill=lit)
        d.line((x + 3, y, x + lean, y - h), fill=deep)

    for x, y, h, lean in ((12, 19, 14, -3), (19, 16, 15, -1), (27, 13, 12, 1), (35, 12, 11, 2), (41, 15, 8, 3),
                          (9, 28, 8, -4), (17, 24, 7, -2)):
        crystal_at(x, y, h, lean)
    for x, y in ((36, 18), (26, 24), (15, 30)):                                         # (its three cores, burning)
        r = 3 if frame == 0 else 2
        d.ellipse((x - r - 1, y - r - 1 + bob, x + r + 1, y + r + 1 + bob), fill=deep)
        d.ellipse((x - r, y - r + bob, x + r, y + r + bob), fill=(232, 168, 255))
        d.point((x, y + bob), fill=(255, 250, 255))
    d.line((30, 28 + bob, 44, 30 + bob), fill=dark, width=2)                            # (a mouth, of a sort)
    for x in (33, 37, 41):
        d.polygon([(x, 29 + bob), (x + 2, 29 + bob), (x + 1, 33 + bob)], fill=lit)
    for x, y, dx in ((18, 32, -4 + swing), (30, 32, 5 - swing)):                        # (the near limbs over it)
        limb(x, y, dx, False)
    return outlined(im)


